def fmt_value(val: float) -> str:
    """Значение отсчёта для файла.

    Единица величины — СУММА oversample отсчётов АЦП, то есть целое число.
    Формат "%g" даёт 6 значащих цифр, и при oversample >= 256 сумма переходит
    10^6: 1048321 записывалось как '1.04832e+06' и читалось обратно как
    1048320 — младший разряд терялся МОЛЧА. Терять его опаснее всего именно
    здесь: сердечная составляющая на порядок слабее дыхательной и живёт как
    раз в младших разрядах, так что ошибка проявилась бы не сбоем, а упавшей
    уверенностью по пульсу — и была бы списана на матрас.
    """
    if val == int(val):
        return str(int(val))
    return repr(val)      # repr float обратимо: round-trip без потери разряда


