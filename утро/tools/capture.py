def build_meta(
    args,
    fw: dict[str, str],
    fs: float,
    fs_source: str,
    source: str,
) -> dict[str, object]:
    started_at, started_source = resolve_started_at(args)
    return {
        "tool_version": TOOL_VERSION,
        "written_by": "утро/tools/capture.py",
        "started_at": started_at,
        "started_at_source": started_source,
        "host_clock_at_write": datetime.now().astimezone().isoformat(timespec="seconds"),
        "fs_hz": f"{fs:g}",
        "fs_source": fs_source,
        "bits": fw.get("bits", ""),
        "oversample": fw.get("oversample", ""),
        "scale": fw.get("scale", ""),
        "value_unit": "сумма oversample отсчётов АЦП (делить на scale для кодов АЦП)",
        "value_min": fw.get("vmin", ""),
        "value_max": fw.get("vmax", ""),
        "index_meaning": "время/(1/fs_hz) от начала потока; разрыв = столько отсчётов потеряно",
        "fw_version": fw.get("fw", "неизвестна"),
        "fw_proto": fw.get("proto", ""),
        "fw_header": fw and " ".join(f"{k}={v}" for k, v in fw.items()) or "",
        "source": source,
        "baud": getattr(args, "baud", "") or "",
        "note": getattr(args, "note", "") or "",
        "ref_resp_bpm": getattr(args, "ref_resp", None),
        "ref_hr_bpm": getattr(args, "ref_hr", None),
    }


def resolve_started_at(args) -> tuple[str, str]:
    """Время старта замера.

    Передаётся аргументом, потому что часы хоста — не то же самое, что время
    замера: ноутбук мог быть разбужен из сна, часовой пояс не настроен, запись
    могла начаться по команде оператора раньше запуска скрипта. Если аргумент
    не задан, берём часы хоста, но ЗАПИСЫВАЕМ В ФАЙЛ, что это именно они.
    """
    raw = getattr(args, "started_at", None)
    if raw:
        try:
            dt = datetime.fromisoformat(raw)
        except ValueError:
            raise SystemExit(
                f"--started-at {raw!r}: ожидается ISO 8601, например "
                "2026-10-04T22:10:00 или 2026-10-04T22:10:00+03:00"
            )
        return dt.isoformat(timespec="seconds"), "аргумент --started-at"
    return (
        datetime.now().astimezone().isoformat(timespec="seconds"),
        "часы хоста (--started-at не задан)",
    )


def cmd_record(args) -> int:
    out_path = Path(args.out).expanduser()
    out_path.parent.mkdir(parents=True, exist_ok=True)

    ser = open_serial(args.port, args.baud)
    reader = SerialReader(ser)
    try:
        spare = wait_for_header(reader)
        if reader.fw_header:
            fw = reader.fw_header
            fs = float(fw.get("fs", FS_EXPECTED_HZ))
            fs_source = "заголовок прошивки"
            print(f"Прошивка: {reader.fw_header_raw}")
        else:
            fw = {}
            if args.assume_fs is None:
                raise SystemExit(
                    "Прошивка не прислала заголовок за 3 с, частота дискретизации "
                    "неизвестна.\nПисать файл с выдуманной частотой нельзя: все "
                    "числа будут неверны пропорционально, и это незаметно.\n"
                    "Проверьте порт и скорость, либо задайте частоту явно и "
                    "осознанно: --assume-fs 200"
                )
            fs = args.assume_fs
            fs_source = "задана вручную (--assume-fs), заголовка не было"
            print(f"Заголовка нет. Частота принята равной {fs:g} Гц по --assume-fs.")

        meta = build_meta(args, fw, fs, fs_source, source=f"{args.port} @ {args.baud}")

        asm = StreamAssembler()
        rows_written = 0
        if not args.no_start:
            ser.reset_input_buffer()
            reader._buf.clear()
            spare = []
            ser.write(CMD_START)
            ser.flush()

        print(
            f"Пишу в {out_path}. "
            + (f"Длительность {args.seconds:g} с. " if args.seconds else "")
            + "Остановить — Ctrl+C."
        )
        deadline = time.monotonic() + args.seconds if args.seconds else None
        last_report = time.monotonic()
        silence = SilenceWatch()
        interrupted = False

        with open(out_path, "w", encoding="utf-8", newline="") as fh:
            write_capture_header(fh, meta)
            writer = csv.writer(fh, lineterminator="\n")
            for idx, val in spare:
                asm.push(idx, val)
                writer.writerow([idx, f"{val:g}"])
                rows_written += 1
            try:
                while True:
                    batch = reader.poll()
                    if batch:
                        silence.saw_data()
                    for idx, val in batch:
                        asm.push(idx, val)
                        writer.writerow([idx, f"{val:g}"])
                        rows_written += 1
                    silence.check()
                    now = time.monotonic()
                    if now - last_report >= 5.0:
                        last_report = now
                        lost = asm.stats.lost
                        warn = f", ПРОПУЩЕНО {lost}" if lost else ""
                        print(
                            f"  {rows_written} отсчётов "
                            f"({rows_written / fs:.0f} с){warn}",
                            flush=True,
                        )
                    if deadline is not None and now >= deadline:
                        break
                    if not reader.ser.in_waiting:
                        time.sleep(0.02)
            except KeyboardInterrupt:
                interrupted = True
                print("\nПрерывание, останавливаю поток.")

            # Остановить прибор и дочитать его прощальную строку "# end":
            # в ней счётчики потерь самой прошивки — независимая проверка
            # нашего разбора индексов.
            try:
                ser.write(CMD_STOP)
                ser.flush()
                tail_deadline = time.monotonic() + 1.0
                while time.monotonic() < tail_deadline:
                    for idx, val in reader.poll():
                        asm.push(idx, val)
                        writer.writerow([idx, f"{val:g}"])
                        rows_written += 1
                    if reader.end_line:
                        break
                    time.sleep(0.05)
            except Exception as exc:                       # pragma: no cover
                print(f"  (не удалось остановить поток штатно: {exc})")

            # Хвостовые метаданные: их значение известно только сейчас.
            # Читатель собирает '#'-строки по всему файлу, не только сверху.
            asm.stats.bad_rows = reader.bad_lines
            fh.write(_meta_line("rows", rows_written))
            fh.write(_meta_line("host_lost_by_index", asm.stats.lost))
            fh.write(_meta_line("host_filled", asm.stats.filled))
            fh.write(_meta_line("host_breaks", asm.stats.breaks))
            fh.write(_meta_line("host_bad_lines", reader.bad_lines))
            fh.write(_meta_line("stopped_at", datetime.now().astimezone().isoformat(timespec="seconds")))
            fh.write(_meta_line("interrupted", "да" if interrupted else "нет"))
            for key, src in (("fw_end_lost", reader.end_line), ("fw_stat_lost", reader.last_stat)):
                if src.get("lost") is not None:
                    fh.write(_meta_line(key, src["lost"]))
            for key in ("lost_pool", "lost_tx", "lost_bad", "ovf"):
                if reader.end_line.get(key) is not None:
                    fh.write(_meta_line(f"fw_end_{key}", reader.end_line[key]))
    finally:
        try:
            ser.close()
        except Exception:                                   # pragma: no cover
            pass

    print(f"Записано {rows_written} отсчётов ({rows_written / fs:.1f} с) в {out_path}")
    if not args.analyze:
        # При --analyze тот же блок печатает разбор ниже; дважды незачем.
        for line in gap_block(
            asm.stats, fs, len(asm.segments),
            len(asm.usable_segments(int(round(args.window * fs)))), args.window,
        ):
            print(line)

    if rows_written == 0:
        print(
            "Ни одного отсчёта. Прошивка молчит: проверьте, что поток запущен "
            "(команда 's'), и что это тот самый порт."
        )
        return 1

    if args.analyze:
        return cmd_replay(
            argparse.Namespace(
                file=str(out_path),
                window=args.window,
                step=args.step,
                fs=None,
                ref_resp=args.ref_resp,
                ref_hr=args.ref_hr,
                quiet_windows=args.quiet_windows,
            )
        )
    print(
        f"\nРазобрать: python3 {Path(__file__).name} replay {out_path} "
        "--ref-resp <вдохов/мин> --ref-hr <пульс с пальца>"
    )
    return EXIT_PULSE_OK


