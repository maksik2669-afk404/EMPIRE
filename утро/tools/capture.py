    # --- 4. Не врёт ли ОСЬ ВРЕМЕНИ ---
    if ref.same_factor is not None:
        k = ref.same_factor
        L += [
            "ЗАМЕР НЕ ДОКАЗАТЕЛЕН: ВРЁТ ОСЬ ВРЕМЕНИ, А НЕ МАТРАС.",
            "",
            f"И дыхание, и пульс разошлись с эталоном в одно и то же число раз "
            f"({k:.3f}).",
            "Физиология так не делает: дыхание и пульс не меняются "
            "одновременно и в одинаковой",
            "пропорции. Одинаковый множитель по обоим каналам даёт только одна "
            "причина — неверная",
            "ось времени, то есть частота дискретизации или потери отсчётов.",
            "",
            "Что сделать:",
            f"  — проверить fs: в шапке отчёта написано, откуда она взята. "
            f"Истинная частота примерно",
            f"    в {k:.3f} раза меньше использованной "
            + (f"({fs_info.hz / k:.2f} Гц вместо {fs_info.hz:g})" if fs_info else "")
            + ";",
            "  — посмотреть блок ЦЕЛОСТНОСТЬ ПОТОКА: потери тоже сжимают ось;",
            "  — записать заново ПОСЛЕ того, как частота подтвердится. "
            "Перезапись с той же fs даст",
            "    то же расхождение.",
        ]
        return EXIT_NO_VERDICT, L

