@dataclass
class RefCheck:
    """Результат сверки с эталоном — ПО КАЖДОМУ КАНАЛУ ОТДЕЛЬНО.

    Один общий флаг «сошлось всё, что можно было сверить» был главным дефектом
    этого инструмента. Если задан только --ref-resp (вдохи посчитать легко, а
    пульсоксиметр нужно ещё найти), то общий флаг вставал в «сошлось», и
    вердикт выдавал «ПУЛЬС ПРОБИВАЕТСЯ, можно закупать этап 2» с кодом 0 — без
    единого слова о том, что найденное число пульса не сверялось НИ С ЧЕМ.
    Частичный эталон давал вывод СИЛЬНЕЕ, чем полное его отсутствие: при
    отсутствии обоих эталонов оговорка хотя бы печаталась.
    Дыхание и пульс проверяют РАЗНЫЕ вещи и не заменяют друг друга:
      — эталон дыхания отвечает «ловим ли мы вообще этого человека»;
      — эталон пульса отвечает «а найденный пик — это сердце?».
    """

    resp_given: bool = False
    resp_ok: bool = False
    resp_got: float | None = None
    resp_ref: float | None = None
    hr_given: bool = False
    hr_ok: bool = False
    hr_got: float | None = None
    hr_ref: float | None = None
    hr_found: bool = False          # DSP вообще выдал число пульса
    same_factor: float | None = None  # одинаковый множитель расхождения
    harmonic_k: int | None = None     # пульс кратен дыханию с этим k

    @property
    def hr_mismatch(self) -> bool:
        """Пик найден, но с эталоном не сошёлся — значит это НЕ пульс."""
        return self.hr_given and self.hr_found and not self.hr_ok


def harmonic_of_breathing(hr: float | None, resp: float | None) -> int | None:
    """Кратен ли найденный пульс найденному дыханию, и во сколько раз.

    Огибающая кардиополосы модулируется дыханием по построению (дыхание двигает
    всю грудную клетку, а значит и амплитуду сердечного толчка), поэтому в её
    спектре всегда стоят линии на частотах, кратных дыханию. При дыхании
    15/мин это 30, 45, 60, 75, 90, 105, 120 уд/мин — семь правдоподобных
    «пульсов» внутри рабочего диапазона 40-130. Такой пик нельзя выдавать за
    успех: он измеряет дыхание, а не сердце.
    Проверено на синтетике: дыхание 15/мин и сердце 60 уд/мин дают ровно
    k = 4, и отличить их по одному спектру нечем — только эталоном с пальца
    или повторным замером, где дыхание другое.
    """
    if hr is None or resp is None or resp <= 0.0:
        return None
    for k in range(HARMONIC_K_MIN, HARMONIC_K_MAX + 1):
        target = k * resp
        tol = max(HARMONIC_TOL_BPM, target * HARMONIC_TOL_FRAC)
        if abs(hr - target) <= tol:
            return k
    return None


def reference_block(
    totals: Totals, ref_resp: float | None, ref_hr: float | None
) -> tuple[list[str], RefCheck]:
    """Сравнение с посчитанным вручную дыханием и пульсом с пальца.

    Без эталона замер ничего не доказывает: найденный пик может оказаться
    чем угодно — наводкой, гармоникой дыхания, вибрацией холодильника.
    """
    lines: list[str] = ["СВЕРКА С ЭТАЛОНОМ"]
    r = RefCheck(
        resp_given=ref_resp is not None,
        hr_given=ref_hr is not None,
        resp_ref=ref_resp,
        hr_ref=ref_hr,
        resp_got=totals.resp_median,
        hr_got=totals.hr_median,
        hr_found=totals.hr_median is not None,
    )
    # Кратность считается ВСЕГДА, эталон для неё не нужен: оба числа свои.
    r.harmonic_k = harmonic_of_breathing(totals.hr_median, totals.resp_median)

    if ref_resp is None and ref_hr is None:
        lines.append(
            "  Эталон не задан ВООБЩЕ. ЗАМЕР НИЧЕГО НЕ ДОКАЗЫВАЕТ: совпадение "
            "числа с правдой не проверено."
        )
        lines.append(
            "  Повторите с --ref-resp <вдохов/мин, посчитано вручную за минуту> "
            "и --ref-hr <пульс с пальца>."
        )
        lines += harmonic_lines(r)
        return lines, r

    if ref_resp is not None:
        got = totals.resp_median
        if got is None:
            lines.append(
                f"  дыхание: эталон {ref_resp:.1f}/мин, измерено — НЕТ. Не сошлось."
            )
        else:
            d = got - ref_resp
            r.resp_ok = abs(d) <= REF_RESP_TOL_BPM
            lines.append(
                f"  дыхание: эталон {ref_resp:.1f}/мин, измерено {got:.1f}/мин, "
                f"разница {d:+.1f} (допуск ±{REF_RESP_TOL_BPM:.0f}) — "
                + ("сходится" if r.resp_ok else "РАСХОДИТСЯ")
            )
            if not r.resp_ok:
                lines.append(
                    "    Дыхание — самая сильная составляющая сигнала, и если "
                    "ОНО не сошлось, мы ловим не этого человека:"
                )
                lines.append(
                    "    не ту частоту дискретизации, не тот файл, плёнку не под "
                    "грудью. О матрасе такая запись не говорит ничего."
                )
    else:
        lines.append(
            "  дыхание: эталон НЕ ЗАДАН (--ref-resp). Не проверено, что найденные "
            "вдохи — это вдохи этого человека."
        )

    if ref_hr is not None:
        got = totals.hr_median
        if got is None:
            lines.append(
                f"  пульс: эталон {ref_hr:.1f} уд/мин, измерено — НЕТ. "
                "Сверять нечего; при сошедшемся дыхании это и есть ответ этапа 1."
            )
        else:
            d = got - ref_hr
            r.hr_ok = abs(d) <= REF_HR_TOL_BPM
            lines.append(
                f"  пульс: эталон {ref_hr:.1f} уд/мин, измерено {got:.1f} уд/мин, "
                f"разница {d:+.1f} (допуск ±{REF_HR_TOL_BPM:.0f}) — "
                + ("сходится" if r.hr_ok else "РАСХОДИТСЯ")
            )
            if not r.hr_ok:
                # Частая и опасная ошибка: детектор огибающей ловит вторую
                # гармонику сердечного толчка или половину частоты. Число
                # выглядит правдоподобным, поэтому проверяем явно.
                for mult, name in ((2.0, "вдвое больше"), (0.5, "вдвое меньше")):
                    if abs(got - ref_hr * mult) <= REF_HR_TOL_BPM * max(1.0, mult):
                        lines.append(
                            f"    Измеренное значение {name} эталона — это похоже на "
                            "гармонику, а не на пульс. Числу верить нельзя."
                        )
                        break
    else:
        lines.append(
            "  пульс: эталон НЕ ЗАДАН (--ref-hr). ГЛАВНОЕ ЧИСЛО ЭТАПА 1 НЕ "
            "СВЕРЕНО НИ С ЧЕМ."
        )
        lines.append(
            "    В полосе 4-20 Гц сидит не только сердце: наводка, гармоника "
            "дыхания, вибрация холодильника через пол."
        )
        lines.append(
            "    Повторите с --ref-hr <пульс с пальца, снятый ОДНОВРЕМЕННО с "
            "записью>."
        )

    # Одинаковый множитель расхождения по обоим каналам — подпись оси времени,
    # а не физиологии. Это самая механическая диагностика, для которой все
    # данные уже есть, и без неё человек перезаписывает ещё десять минут,
    # потому что в списке причин названо всё, кроме действующей.
    if (
        ref_resp is not None
        and ref_hr is not None
        and totals.resp_median is not None
        and totals.hr_median is not None
        and not r.resp_ok
        and not r.hr_ok
        and ref_resp > 0
        and ref_hr > 0
    ):
        k_resp = totals.resp_median / ref_resp
        k_hr = totals.hr_median / ref_hr
        if abs(k_resp - k_hr) <= RATIO_MATCH_TOL * max(k_resp, k_hr):
            r.same_factor = (k_resp + k_hr) / 2.0
            lines.append(
                f"    ОБА числа разошлись в ОДНО И ТО ЖЕ число раз "
                f"({k_resp:.3f} по дыханию и {k_hr:.3f} по пульсу)."
            )
            lines.append(
                "    Это не физиология: дыхание и пульс не меняются "
                "одновременно и в одинаковой пропорции. Так выглядит"
            )
            lines.append(
                "    ОСЬ ВРЕМЕНИ — неверная fs или потери отсчётов. "
                "Проверьте fs (см. шапку отчёта и ключ --fs)"
            )
            lines.append(
                "    и блок ЦЕЛОСТНОСТЬ ПОТОКА. Перезапись той же ошибки не "
                "лечит."
            )

    lines += harmonic_lines(r)

    if (r.resp_given and not r.resp_ok) or (r.hr_given and not r.hr_ok):
        lines.append(
            "  Пока эталон не сошёлся, вердикт ниже — про цифры DSP, а не про "
            "человека на матрасе."
        )
    return lines, r


def harmonic_lines(r: RefCheck) -> list[str]:
    """Строки про кратность пульса дыханию."""
    if r.harmonic_k is None:
        return []
    L = [
        f"  КРАТНОСТЬ: найденный пульс {r.hr_got:.1f} уд/мин — это ровно "
        f"{r.harmonic_k}-я гармоника найденного дыхания",
        f"    ({r.resp_got:.1f}/мин * {r.harmonic_k} = "
        f"{r.resp_got * r.harmonic_k:.1f}). Огибающая кардиополосы "
        "модулируется дыханием,",
        "    поэтому такие линии в её спектре есть ВСЕГДА, и по одному спектру "
        "гармонику дыхания от сердца",
        "    не отличить.",
    ]
    if r.hr_given and r.hr_ok:
        L.append(
            "    Но число сошлось с пульсом с пальца, то есть здесь пульс "
            "человека и гармоника дыхания просто совпали."
        )
        L.append(
            "    На следующем замере стоит развести их: попросить человека "
            "дышать чуть чаще или реже."
        )
    else:
        L.append(
            "    Эталоном это число не подтверждено, поэтому считать его "
            "пульсом НЕЛЬЗЯ."
        )
    return L


