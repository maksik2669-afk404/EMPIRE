@dataclass
class GapStats:
    """Счётчики целостности оси времени."""

    rows: int = 0               # сколько отсчётов принято (битые не считаются)
    lost: int = 0               # сколько отсчётов прошивка не доставила
    filled: int = 0             # сколько из них восстановлено интерполяцией
    lost_split: int = 0         # сколько потеряно в длинных пропусках (разрез)
    breaks: int = 0             # сколько раз запись разрезана длинным пропуском
    restarts: int = 0           # поток перезапускали командой 's' (индекс с нуля)
    odd_index: int = 0          # строка с неправдоподобным индексом, выброшена
    bad_rows: int = 0           # строка данных не разобралась
    # Пропуск длиннее huge_gap не начисляется в lost вовсе: такой разрыв
    # означает, что индекс пришёл неправдоподобно далёкий, и подставлять его
    # в долю потерь значит выдумывать число, большее длины записи.
    lost_unknown: int = 0
    unknown_breaks: int = 0

    @property
    def expected(self) -> int:
        """Сколько отсчётов должно было прийти, если бы потерь не было.

        Разрывы неизвестной длины (lost_unknown) сюда НЕ входят: их длина и
        есть неизвестная величина, а деление на неё дало бы правдоподобное
        число там, где его нет.
        """
        return self.rows + self.lost

    @property
    def lost_fraction(self) -> float:
        return self.lost / self.expected if self.expected else 0.0

    def merge(self, other: "GapStats") -> None:
        self.rows += other.rows
        self.lost += other.lost
        self.filled += other.filled
        self.lost_split += other.lost_split
        self.breaks += other.breaks
        self.restarts += other.restarts
        self.odd_index += other.odd_index
        self.bad_rows += other.bad_rows
        self.lost_unknown += other.lost_unknown
        self.unknown_breaks += other.unknown_breaks


@dataclass
class Segment:
    """Непрерывный по времени отрезок: values[i] соответствует моменту
    (start_index + i) / fs от начала потока. Пропуски уже заполнены."""

    start_index: int
    values: list[float] = field(default_factory=list)
    filled: list[bool] = field(default_factory=list)

    def __len__(self) -> int:
        return len(self.values)


class StreamAssembler:
    """Превращает поток пар (индекс, значение) в непрерывные отрезки.

    Индекс из прошивки — НЕ счётчик принятых отсчётов, а временная координата:
    индекс k означает момент t0 + k/fs. Поэтому разрыв индексов равен числу
    потерянных отсчётов, и это единственный способ узнать о потере: по самим
    данным она не видна, сигнал останется правдоподобным.

    ОБРАТНЫЙ СКАЧОК ИНДЕКСА РАЗБИРАЕТСЯ, А НЕ СВАЛИВАЕТСЯ В ОДИН СЛУЧАЙ.
    Индекс, который не вырос, означает одно из двух, и это РАЗНЫЕ вещи:
      — перезапуск потока (команда 's' обнуляет индекс) — тогда дальше
        последовательность растёт от нового, маленького значения;
      — одиночная битая строка (потерянная цифра в порту: 30000 -> 3000) —
        тогда следующая строка продолжает ПРЕЖНЮЮ последовательность.
    Если не различать, одна битая цифра даёт катастрофу в отчёте: шаг от
    маленького индекса к настоящему читается как потеря 27000 отсчётов, то
    есть «потеряно больше, чем длина записи», плюс два лишних разреза.
    Проверено на синтетике: запись 300 с, одна строка с индексом 3000 вместо
    30000 — до этой правки отчёт объявлял 31% потерь и требовал сменить
    кабель, потеряно не было НИЧЕГО.
    Поэтому подозрительный отсчёт не применяется сразу, а откладывается, и
    решение принимается по следующим строкам.
    """

    # Сколько подряд идущих отсчётов от нового маленького индекса считать
    # доказательством перезапуска. Один — не доказательство (ровно так
    # выглядит битая строка), три — уже последовательность, которую случайный
    # мусор в порту не подделает. Цена ошибки несимметрична: лишний разрез
    # теряет до двух окон, а невыброшенный мусор выдумывает потери.
    RESTART_CONFIRM_ROWS = 3

    def __init__(
        self,
        max_fill: int = GAP_FILL_MAX_SAMPLES,
        fs: float = FS_EXPECTED_HZ,
        huge_gap_s: float = 10.0,
    ) -> None:
        self.max_fill = max_fill
        # Пропуск длиннее этого считается разрывом неизвестной длины: при
        # 200 Гц это 2000 отсчётов. Десять секунд выбраны так, чтобы любой
        # настоящий сбой порта (переполнение буфера драйвера — десятки
        # миллисекунд) остался внутри, а неправдоподобный индекс — снаружи.
        # Значение — решение, на железе НЕ проверено.
        self.huge_gap = max(self.max_fill + 1, int(round(huge_gap_s * fs)))
        self.stats = GapStats()
        self.segments: list[Segment] = []
        self._cur: Segment | None = None
        self._prev_index: int | None = None
        # Отложенные отсчёты: индекс не вырос, и пока неизвестно, перезапуск
        # это или мусор.
        self._pending: list[tuple[int, float]] = []

    def push(self, index: int, value: float) -> bool:
        """Добавить отсчёт. Возвращает True, если отрезок был разорван.

        Отсчёт может быть отложен (см. RESTART_CONFIRM_ROWS): тогда он не
        попадёт в отрезок немедленно. Перед разбором обязателен flush().
        """
        if self._cur is None or self._prev_index is None:
            self._open(index, value)
            return False

        if self._pending:
            return self._push_while_pending(index, value)

        if index > self._prev_index:
            return self._advance(index, value)

        # Индекс не вырос — решение откладываем до следующих строк.
        self._pending = [(index, value)]
        return False

    def _push_while_pending(self, index: int, value: float) -> bool:
        held = self._pending
        if index > self._prev_index:
            # Прежняя последовательность продолжилась — значит отложенные
            # строки были мусором. Выбрасываем их, не разрезая отрезок и не
            # начисляя потерь.
            self.stats.odd_index += len(held)
            self._pending = []
            return self._advance(index, value)

        if index > held[-1][0]:
            held.append((index, value))
            if len(held) < self.RESTART_CONFIRM_ROWS:
                return False
            # Перезапуск подтверждён: последовательность уверенно растёт от
            # нового маленького индекса. Открываем отрезок первым отложенным
            # отсчётом; шаг назад в потерю не превращается.
            self._pending = []
            self.stats.restarts += 1
            first_idx, first_val = held[0]
            self._open(first_idx, first_val)
            for idx, val in held[1:]:
                self._advance(idx, val)
            return True

        # Не продолжает ни прежнюю последовательность, ни отложенную — мусор.
        self.stats.odd_index += 1
        return False

    def flush(self) -> None:
        """Разобраться с отложенными отсчётами в конце потока.

        Вызывать ОБЯЗАТЕЛЬНО перед анализом: иначе последние две строки
        перезапущенного потока молча не попадут в отрезки. Если отложенных
        меньше, чем нужно для доказательства перезапуска, они считаются
        мусором — и это честнее, чем открыть отрезок на одной строке.
        """
        held = self._pending
        self._pending = []
        if not held:
            return
        if len(held) >= 2:
            self.stats.restarts += 1
            first_idx, first_val = held[0]
            self._open(first_idx, first_val)
            for idx, val in held[1:]:
                self._advance(idx, val)
        else:
            self.stats.odd_index += len(held)

    def _advance(self, index: int, value: float) -> bool:
        """Применить отсчёт с индексом СТРОГО больше предыдущего."""
        assert self._cur is not None and self._prev_index is not None
        step = index - self._prev_index
        missing = step - 1
        if missing == 0:
            self._cur.values.append(value)
            self._cur.filled.append(False)
            self._prev_index = index
            self.stats.rows += 1
            return False

        if missing <= self.max_fill:
            self.stats.lost += missing
            prev_value = self._cur.values[-1]
            for k in range(1, missing + 1):
                # Линейная вставка: сохраняет ось времени ценой того, что
                # на длине пропуска сигнала нет. Это честнее, чем сдвиг.
                self._cur.values.append(prev_value + (value - prev_value) * k / step)
                self._cur.filled.append(True)
            self.stats.filled += missing
            self._cur.values.append(value)
            self._cur.filled.append(False)
            self._prev_index = index
            self.stats.rows += 1
            return False

        self.stats.breaks += 1
        if missing <= self.huge_gap:
            self.stats.lost += missing
            self.stats.lost_split += missing
        else:
            # Разрыв неизвестной длины. В долю потерь не идёт: индекс мог
            # прийти испорченным, и начислить 27000 потерь на запись из
            # 60000 отсчётов значит соврать громче, чем промолчать.
            self.stats.lost_unknown += missing
            self.stats.unknown_breaks += 1
        self._open(index, value)
        return True

    def _open(self, index: int, value: float) -> None:
        seg = Segment(start_index=index, values=[value], filled=[False])
        self.segments.append(seg)
        self._cur = seg
        self._prev_index = index
        self.stats.rows += 1

    def usable_segments(self, min_len: int) -> list[Segment]:
        return [s for s in self.segments if len(s) >= min_len]


