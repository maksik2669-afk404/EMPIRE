RAW_RATE_MIN_HZ = 1000.0
# Время установления тракта по §2.4: τ = 10.1 с, до 1 % нужно 4.6 τ = 46 с.
# Столько же стоит в прошивке (UTRO_SETTLE_MS). Здесь значение нужно только
# как запасное, если заголовок прошивки не пришёл: пока идёт установление,
