WINDOW_FILL_REJECT = 0.05

# Порог вердикта: если пульс определился меньше чем в 30% окон — считаем, что
# на этом матрасе пульса не будет.
# ОТКУДА 30%: это решение ЭТОГО инструмента, а не продукта. В
# КОМПОНЕНТЫ-УТРО.md (раздел «Этап 1», п.5) критерий сформулирован иначе —
# «если hr_bpm возвращает None на этом матрасе, пульса не будет», без
