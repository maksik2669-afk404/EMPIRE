def add_common_analysis_args(p: argparse.ArgumentParser) -> None:
    p.add_argument(
        "--window", type=float, default=WINDOW_S_DEFAULT,
        help="длина окна анализа, с (по умолчанию 60; минимум 20 — требование analyze_window)",
    )
    p.add_argument(
        "--step", type=float, default=STEP_S_DEFAULT,
        help="шаг между окнами, с (по умолчанию 30)",
    )
    p.add_argument(
        "--ref-resp", type=float, default=None, metavar="ВДОХОВ_В_МИН",
        help="эталон: вдохов в минуту, посчитано вручную за минуту",
    )
    p.add_argument(
        "--ref-hr", type=float, default=None, metavar="УД_В_МИН",
        help="эталон: пульс с пальца, ударов в минуту",
    )
    p.add_argument(
        "--quiet-windows", action="store_true",
        help="не печатать строку на каждое окно, только итог и вердикт",
    )


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        prog="capture.py",
        description=(
            "Проверочный стенд «Утро», этап 1: запись сигнала плёнки PVDF с "
            "ESP32-S3 и прогон через morning.dsp. Отвечает на один вопрос — "
            "пробивается ли пульс через этот матрас."
        ),
        epilog=(
            "Коды возврата: 0 пульс есть; 10 пульса нет (продукт состоятелен "
            "без него, но планы менять); 11 нет дыхания — проблема в тракте "
            "или укладке; 12 вердикта нет (данных мало или эталон не сошёлся); "
            "1 ошибка запуска или формата; 2 ошибка в аргументах."
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    sub = p.add_subparsers(dest="mode", required=True)

    # --- record ---
    rec = sub.add_parser(
        "record", help="писать поток с порта в файл",
        description="Записать сигнал с ESP32-S3 в CSV с заголовком-метаданными.",
    )
    rec.add_argument("--port", required=True, help="порт, например /dev/ttyACM0 или COM5")
    rec.add_argument(
        "--baud", type=int, default=460800,
        help="скорость порта (по умолчанию 460800 — как в прошивке; при старом мосте CH340 ставить 115200)",
    )
    rec.add_argument("--out", required=True, help="куда писать CSV")
    rec.add_argument(
        "--seconds", type=float, default=0.0,
        help="сколько писать, с (0 = до Ctrl+C). Рабочий замер — 600",
    )
    rec.add_argument(
        "--started-at", default=None, metavar="ISO8601",
        help=(
            "время начала замера, например 2026-10-04T22:10:00. Передаётся "
            "аргументом, потому что часы хоста могут врать; если не задано, "
            "берутся часы хоста и это помечается в файле"
        ),
    )
    rec.add_argument("--note", default="", help="пометка в файл: матрас, укладка, кто лежал")
    rec.add_argument(
        "--assume-fs", type=float, default=None, metavar="ГЦ",
        help="принять частоту дискретизации, если прошивка не прислала заголовок (осознанно!)",
    )
    rec.add_argument(
        "--no-start", action="store_true",
        help="не посылать команду 's' (поток уже запущен из терминала)",
    )
    rec.add_argument("--analyze", action="store_true", help="сразу разобрать записанное")
    add_common_analysis_args(rec)
    rec.set_defaults(func=cmd_record)

    # --- replay ---
    rep = sub.add_parser(
        "replay", help="разобрать ранее записанный файл",
        description="Прогнать записанный CSV через analyze_window и выдать вердикт.",
    )
    rep.add_argument("file", help="CSV, записанный режимом record")
    rep.add_argument(
        "--fs", type=float, default=None, metavar="ГЦ",
        help="переопределить частоту из файла (только если точно знаете, что в файле она неверна)",
    )
    add_common_analysis_args(rep)
    rep.set_defaults(func=cmd_replay)

    # --- live ---
    liv = sub.add_parser(
        "live", help="живой режим: поток с порта и оценка каждые 30 с",
        description=(
            "Смотреть оценку по мере записи. Нужен, чтобы подобрать укладку "
            "плёнки, не записывая каждый раз по 10 минут."
        ),
    )
    liv.add_argument("--port", required=True, help="порт, например /dev/ttyACM0")
    liv.add_argument("--baud", type=int, default=460800, help="скорость порта")
    liv.add_argument("--out", default=None, help="заодно писать всё в этот CSV")
    liv.add_argument(
        "--seconds", type=float, default=0.0,
        help="сколько смотреть, с (0 = до Ctrl+C)",
    )
    liv.add_argument("--started-at", default=None, metavar="ISO8601", help="время начала замера")
    liv.add_argument("--note", default="", help="пометка в файл")
    liv.add_argument("--assume-fs", type=float, default=None, metavar="ГЦ",
                     help="принять частоту, если заголовка не было")
    liv.add_argument("--no-start", action="store_true", help="не посылать команду 's'")
    add_common_analysis_args(liv)
    liv.set_defaults(func=cmd_live)

    return p


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    if args.step <= 0:
        raise SystemExit("--step должен быть больше нуля")
    if args.window <= 0:
        raise SystemExit("--window должен быть больше нуля")
    return args.func(args)


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except KeyboardInterrupt:
        # Ctrl+C вне цикла записи: молча выйти, а не сыпать трассировкой.
        raise SystemExit(130)
