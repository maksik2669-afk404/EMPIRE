EXIT_PULSE_OK = 0
EXIT_NO_PULSE = 10
EXIT_NO_BREATHING = 11
EXIT_NO_VERDICT = 12

TRACT_DOC = "утро/АНАЛОГОВЫЙ-ТРАКТ.md"


def verdict(
    totals: Totals,
    ref_ok: bool,
    ref_given: bool,
    hr_ref_mismatch: bool = False,
    window_s: float = WINDOW_S_DEFAULT,
    step_s: float = STEP_S_DEFAULT,
) -> tuple[int, list[str]]:
    """ГЛАВНЫЙ ВЕРДИКТ этапа 1 человеческим языком.

    Возвращает (код возврата, строки). Порядок проверок важен: сначала
    «а сигнал-то есть?», и только потом «пробивается ли пульс». Иначе мёртвый
    тракт будет осуждён как плохой матрас, и человек выбросит матрас вместо
    того, чтобы пропаять зарядовый усилитель.
    """
    L: list[str] = ["", "=" * 72, "ГЛАВНЫЙ ВЕРДИКТ", "=" * 72]

    if totals.counted == 0:
        # Сколько окон даёт десятиминутный замер при этих настройках —
        # чтобы человек видел, на что рассчитывать, а не угадывал.
        per_10min = max(0, int((600.0 - window_s) // step_s) + 1)
        L += [
            "Ни одного пригодного окна. Вердикта нет.",
            f"Нужно не меньше {window_s:g} секунд подряд без длинных "
            f"пропусков; замер на 10 минут при шаге {step_s:g} с даёт "
            f"{windows_nom(per_10min)}.",
            "Если окна были, но все отброшены — слишком много потерь в порту: "
            "снизьте скорость до 115200 (UTRO_SERIAL_BAUD в прошивке) или "
            "смените USB-кабель.",
        ]
        return EXIT_NO_VERDICT, L

    # --- 1. Жив ли тракт вообще ---
    # Эта проверка идёт ПЕРВОЙ и до всякого разговора о пульсе. Дыхание на
    # порядок сильнее сердечной составляющей: если не проходит даже оно, запись
    # говорит о тракте и укладке, а не о матрасе. Перепутав эти два случая,
    # человек выбросит матрас вместо того, чтобы пропаять зарядовый усилитель.
    if totals.resp_found == 0 or totals.resp_fraction < RESP_SHAKY:
        if totals.resp_found == 0:
            L += [
                "ДЫХАНИЕ НЕ НАЙДЕНО НИ В ОДНОМ ОКНЕ.",
                "",
                "Это НЕ приговор матрасу: о матрасе эта запись не говорит",
                "ничего. Дыхание сильнее пульса на порядок, и если не проходит",
                "даже оно, сигнала нет вообще.",
            ]
        else:
            L += [
                f"ДЫХАНИЕ ЛОВИТСЯ НЕУСТОЙЧИВО: {windows_nom(totals.resp_found)} "
                f"из {totals.counted} ({totals.resp_fraction * 100:.0f}%).",
                "",
                "Это НЕ приговор матрасу. Дыхание — самая сильная составляющая",
                "сигнала; если оно пропадает, мы мерили бы качество укладки, а",
                "не матрас. Самое вероятное — плёнка лежит не под грудью,",
                "передавлена или уехала.",
            ]
            if totals.resp_values:
                L.append("")
                L.append(
                    f"    Найденные значения ({min(totals.resp_values):.1f}…"
                    f"{max(totals.resp_values):.1f}/мин) в этом случае скорее"
                )
                L.append(
                    "    всплески шума, чем дыхание: у живого сигнала дыхание"
                )
                L.append("    находится почти в каждом окне.")
        L += [
            "",
            "Куда идти: " + TRACT_DOC + ", раздел проверки тракта. Там же —",
            "последовательность, в которой это ловится:",
            "  1. Зарядовый усилитель вообще есть и запитан? PVDF отдаёт ЗАРЯД,",
            "     напрямую на АЦП плёнка не работает — это не опция, без него",
            "     на входе только наводка сети.",
            "  2. Команда прошивки \"c 10\" без человека: смещение около",
            "     середины диапазона, СКО не нулевое. Нулевое СКО = вход висит",
            "     в воздухе или усилитель не питается.",
            "  3. Наводка 50 Гц в отчёте калибровки мала? Экран кабеля на землю",
            "     усилителя с ОДНОЙ стороны, провода до плёнки короткие.",
            "  4. Плёнка под матрасом на уровне ГРУДИ и не передавлена.",
            "  5. Команда \"c 30\" с человеком: размах не больше половины",
            "     диапазона. Если упёрся — уменьшить усиление: дыхание",
            "     насыщает тракт и топит пульс.",
            "",
            "После каждого шага — запись на 2-3 минуты и прогон этим же",
            "инструментом. Пока дыхание не ловится устойчиво, о пульсе",
            "говорить нечего.",
        ]
        return EXIT_NO_BREATHING, L

    # --- 2. Главный вопрос этапа 1 ---
    frac = totals.hr_fraction
    L.append(
        f"Пульс определился в {windows_prep(totals.hr_found)} из "
        f"{totals.counted} ({frac * 100:.0f}%). "
        f"Порог решения — {HR_VERDICT_FAIL * 100:.0f}%."
    )
    L.append("")

    if frac < HR_VERDICT_FAIL:
        # Перед приговором матрасу — проверка, не съело ли окна шевеление.
        # analyze_window не ищет пульс при motion=True и при двух людях; если
        # таких окон большинство, запись просто непригодна для вопроса.
        if totals.hr_eligible < max(3, totals.counted * 0.3):
            L += [
                "НА ЭТОЙ ЗАПИСИ ВОПРОС НЕ РЕШАЕТСЯ.",
                "",
                "Окон, в которых DSP вообще имел право искать пульс (один",
                f"человек, без шевеления), всего {totals.hr_eligible} из "
                f"{totals.counted}.",
                "Остальные съело шевеление или второй человек в постели.",
                "Записать заново: один человек, лежать неподвижно 10 минут,",
                "не разговаривать. Матрас здесь ни при чём.",
            ]
            return EXIT_NO_VERDICT, L

        L += [
            "НА ЭТОМ МАТРАСЕ ПУЛЬСА НЕ БУДЕТ.",
            "",
            "Сердечный толчок до плёнки не доходит: матрас его гасит. Это",
            "свойство матраса, а не ошибка сборки — дыхание-то проходит.",
            "",
            "ПРОДУКТ ОТ ЭТОГО НЕ УМИРАЕТ. «Утро» остаётся состоятельным без",
            "пульса: дыхание, сон, присутствие и вес — это уже весь продукт.",
            "Утренняя сводка родне и ночные тревоги строятся на них, а не на",
            "пульсе.",
            "",
            "НО ПЛАНЫ НАДО МЕНЯТЬ, И ДО ЗАКУПКИ ЭТАПА 2:",
            "  — выбросить пульс из обещаний продукта и из текстов сводки;",
            "  — присутствие в постели теперь держится только на дыхании и на",
            "    тензодатчиках под ножками, значит тензодатчики из",
            "    «желательно» становятся «обязательно»;",
            "  — если пульс нужен принципиально — это другой датчик (браслет",
            "    или резистивная полоса) и другой разговор про деньги;",
            "  — прежде чем ставить крест: попробовать другой матрас или",
            "    плёнку поверх матраса под простынёй. Это полчаса работы и",
            "    ещё одна запись этим же инструментом.",
        ]
        return EXIT_NO_PULSE, L

    if frac < HR_VERDICT_GOOD:
        L += [
            "ПУЛЬС ПРОБИВАЕТСЯ, НО НЕУСТОЙЧИВО.",
            "",
            f"{frac * 100:.0f}% окон — это выше порога ({HR_VERDICT_FAIL * 100:.0f}%), "
            "то есть матрас сигнал пропускает,",
            "но на таком проценте строить продуктовое обещание рано.",
            "",
            "Что сделать до закупки этапа 2:",
            "  — переложить плёнку на пару сантиметров (положение под грудью",
            "    решает больше, чем всё остальное) и записать ещё раз;",
            "  — проверить усиление командой \"c 30\": если дыхание занимает",
            "    почти весь диапазон АЦП, пульс тонет в младшем разряде;",
            "  — записать 20 минут вместо 10: больше окон — честнее доля.",
        ]
    else:
        L += [
            "ПУЛЬС ПРОБИВАЕТСЯ ЧЕРЕЗ ЭТОТ МАТРАС.",
            "",
            "Главный открытый риск этапа 1 закрыт: сердечный толчок доходит до",
            "плёнки и выделяется устойчиво. Можно закупать этап 2.",
        ]

    if hr_ref_mismatch:
        # Пик есть, но он не совпал с пульсом с пальца. Значит найден НЕ пульс:
        # в кардиополосе 4-20 Гц сидит что угодно — наводка, гармоника толчка,
        # вибрация от холодильника через пол. Объявить в этом месте «пульс
        # пробивается» значит закупить этап 2 под цифру, которая ничего не
        # измеряет. Поэтому уверенный вердикт здесь снимается.
        L += [
            "",
            "НО ЭТО НЕ ПУЛЬС ЧЕЛОВЕКА — ВОПРОС ОСТАЁТСЯ ОТКРЫТЫМ.",
            "",
            "Найденное число не сошлось с пульсом с пальца (см. сверку выше).",
            "В полосе 4-20 Гц сидит не только сердце: наводка, гармоника",
            "сердечного толчка, вибрация от холодильника или стиральной машины",
            "через пол. Устойчивый пик — ещё не пульс.",
            "",
            "Что сделать:",
            "  — пересчитать эталон: пульс с пальца снимать В ТО ЖЕ ВРЕМЯ, что",
            "    и запись, а не до и не после;",
            "  — проверить, не кратно ли измеренное эталону (это гармоника);",
            "  — записать заново и сверить снова. Пока не сойдётся, считать,",
            "    что ответа на вопрос этапа 1 нет.",
        ]
        return EXIT_NO_VERDICT, L

    if ref_given and not ref_ok:
        L += [
            "",
            "ОГОВОРКА: эталон сошёлся не полностью. Пик найден, но что это",
            "именно пульс человека — не доказано. Пересчитайте вручную и",
            "повторите замер, прежде чем верить числу.",
        ]
    elif not ref_given:
        L += [
            "",
            "ОГОВОРКА: эталон не задавался. Без ручного подсчёта вдохов и пульса",
            "с пальца этот вердикт — про поведение алгоритма, а не про человека.",
        ]
    return EXIT_PULSE_OK, L


