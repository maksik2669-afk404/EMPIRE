# CSV с заголовком-метаданными. Строки, начинающиеся с '#', — метаданные вида
# "# ключ=значение"; они могут стоять и в конце файла (туда дописываются
# счётчики потерь, которые известны только после остановки потока). Дальше —
# обычный CSV: строка имён колонок "index,value" и строки данных.
# Единица значения — СУММА oversample отсчётов АЦП (так отдаёт прошивка);
# для вольт делить на scale и умножать на full_scale_mv/adc_max. Для dsp.py
# масштаб не важен, он инвариантен к усилению.

def _meta_line(key: str, value: object) -> str:
    """Строка метаданных. Значение ОБЯЗАНО быть одной строкой.

    Без этой защиты любая пометка оператора становится оружием: --note с
    переводом строки и текстом "# fs_hz=50" дописывает в файл второй fs_hz, и
    запись на 200 Гц читается как запись на 50 Гц — ось времени вчетверо, все
    частоты вчетверо, молча. Проверено до правки: получалось «100.0 с при
    50 Гц» вместо 25 с при 200 Гц.
    Перевод строки и возврат каретки заменяются пробелом, а не отвергаются:
    терять пометку человека из-за случайного Enter дороже, чем её выровнять.
    """
    key = str(key)
    if "=" in key or "\n" in key or "\r" in key:
        raise ValueError(f"ключ метаданных {key!r} содержит '=' или перевод строки")
    text = str(value).replace("\r", " ").replace("\n", " ")
    return f"# {key}={text}\n"


# Ключи, которые задают СМЫСЛ чисел в файле. Два разных значения такого ключа
# в одном файле — это не «последний победил», а вопрос «какой верен», на
# который догадываться нельзя (см. read_capture).
META_CRITICAL_KEYS = (
    "fs_hz", "fs_kind", "fs_confirmed", "bits", "oversample", "scale",
    "value_min", "value_max", "axis_hz",
)


def write_capture_header(fh, meta: dict[str, object]) -> None:
    fh.write(_meta_line(CSV_MAGIC, CSV_FORMAT_VERSION))
    for key, value in meta.items():
        if value is None:
            continue
        fh.write(_meta_line(key, value))
    fh.write(",".join(CSV_COLUMNS) + "\n")


def read_capture(
    path: Path,
) -> tuple[dict[str, str], list[tuple[int, float]], list[str], int]:
    """Прочитать файл записи.

    Возвращает (метаданные, строки, прочие комментарии, число битых строк).
    Ничего не угадывает: неизвестный формат — ошибка, а не предположение.
    """
    meta: dict[str, str] = {}
    comments: list[str] = []
    rows: list[tuple[int, float]] = []
    bad = 0
    seen_magic = 0

    def data_lines(fh):
        nonlocal seen_magic
        for raw in fh:
            s = raw.strip()
            if not s:
                continue
            if s.startswith("#"):
                body = s.lstrip("#").strip()
                if "=" in body:
                    k, v = body.split("=", 1)
                    k = k.strip()
                    v = v.strip()
                    if k:
                        if k == CSV_MAGIC:
                            seen_magic += 1
                            if seen_magic > 1:
                                raise ValueError(
                                    f"{path}: в файле две строки "
                                    f"'# {CSV_MAGIC}=...', то есть две записи, "
                                    "склеенные вместе (например 'cat а.csv "
                                    "б.csv > оба.csv'). Индексы и частоты у них "
                                    "свои, разобрать это как одну запись нельзя."
                                )
                        # Дубликат критичного ключа с ДРУГИМ значением — отказ.
                        # Формат допускает '#'-строки в конце файла (туда
                        # дописываются счётчики потерь), поэтому дубли ключей —
                        # штатная часть формата, и правило «последний победил»
                        # для fs_hz означало бы молчаливую подмену оси времени.
                        if (
                            k in META_CRITICAL_KEYS
                            and k in meta
                            and meta[k] != v
                        ):
                            raise ValueError(
                                f"{path}: ключ {k} встречается дважды с разными "
                                f"значениями ({meta[k]!r} и {v!r}). Какое верно "
                                "— догадываться нельзя: от этого зависят все "
                                "числа отчёта. Почините файл."
                            )
                        meta[k] = v
                        continue
                comments.append(body)
                continue
            yield raw

    with open(path, "r", encoding="utf-8", newline="") as fh:
        reader = csv.reader(data_lines(fh))
        first = True
        for row in reader:
            if first:
                first = False
                if [c.strip() for c in row[:2]] == list(CSV_COLUMNS):
                    continue
                # Заголовка колонок нет — файл писал не этот инструмент.
            if len(row) < 2:
                bad += 1
                continue
            try:
                rows.append((int(row[0]), float(row[1])))
            except ValueError:
                bad += 1

    if CSV_MAGIC not in meta:
        raise ValueError(
            f"{path}: это не запись «Утро» — нет строки '# {CSV_MAGIC}=...'. "
            "Читать такой файл без догадок нельзя."
        )
    return meta, rows, comments, bad


