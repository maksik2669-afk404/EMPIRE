RAW_RATE_EXPECTED_HZ = 4000.0
MAINS_HZ = 50.0
SUM_LEN_EXPECTED = 80
# Выше этой частоты файл считается сырым потоком, ниже — выходным. Граница
# взята посередине между 200 и 4000 по логарифму (≈894); круглые 1000 Гц от
# неё недалеко и читаются человеком. Никакой физики в границе нет: она только
