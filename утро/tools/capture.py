# Огибающая кардиополосы по построению модулируется дыханием, поэтому в её
# спектре всегда есть линии на частотах, кратных дыханию: при дыхании 15/мин
# это 30, 45, 60, 75, 90, 105, 120 уд/мин — семь правдоподобных «пульсов» в
# рабочем диапазоне 40-130. Такой пик надо помечать как подозрительный, а не
# выдавать как успех. Диапазон k: при дыхании 10-25/мин и пульсе 40-130
# отношение лежит в 2…13.
HARMONIC_K_MIN = 2
HARMONIC_K_MAX = 13
# Допуск кратности. Сетка спектра дыхания в dsp.py — 0.005 Гц (0.3 вдоха/мин),
