def open_serial(port: str, baud: int):
    """Ленивый импорт pyserial.

    Импорт именно здесь, а не наверху файла: режим replay — работа с уже
    записанным файлом — обязан работать на машине, где pyserial не стоит
    (например, когда запись привезли на другой компьютер). Наверху импорт
    уронил бы и replay.
    """
    try:
        import serial  # type: ignore
    except ImportError:
        raise SystemExit(
            "Для работы с портом нужен pyserial, его нет.\n"
            "  python3 -m pip install pyserial\n"
            "  (в Debian/Ubuntu: sudo apt install python3-serial)\n"
            "Разбор уже записанного файла (режим replay) работает и без него."
        )

    try:
        from serial.tools import list_ports  # type: ignore
    except ImportError:
        list_ports = None

    try:
        # timeout=0.2 — не блокируемся навсегда: нужно успевать реагировать на
        # Ctrl+C и на таймер длительности записи.
        return serial.Serial(port, baud, timeout=0.2)
    except Exception as exc:
        msg = [f"Не удалось открыть порт {port} на {baud} бод: {exc}"]
        if list_ports is not None:
            found = [f"{p.device} — {p.description}" for p in list_ports.comports()]
            if found:
                msg.append("Доступные порты:")
                msg += ["  " + f for f in found]
            else:
                msg.append(
                    "Портов не видно вообще. Проверьте кабель (бывают "
                    "зарядные без данных) и права: обычно нужна группа "
                    "dialout/uucp."
                )
        raise SystemExit("\n".join(msg))


def parse_fw_header(line: str) -> dict[str, str]:
    """Разобрать строку-заголовок прошивки (proto=2).

    # utro-stage1 fw=2.0.0 proto=2 fs=200 fs_src=nominal oversample=80
    #   sum_len=80 decim=20 raw_fs=4000 mains_hz=50 bits=12 scale=80 vmin=0
    #   vmax=327600 gpio=4 adc=1 ch=3 atten_db=12 fmt=index,sum
    #   settle_ms=46000 sq_pin=9 transport=usb_cdc baud=460800
    Тем же разбором читаются строки "# stat", "# end", "# raw begin" и
    "# begin": формат у них один — токены вида ключ=значение.
    """
    out: dict[str, str] = {}
    for token in line.split():
        if "=" in token:
            k, v = token.split("=", 1)
            out[k] = v
    return out


def fw_header_fs(fw: dict[str, str], assume_fs: float | None) -> tuple[float, str]:
    """НОМИНАЛЬНАЯ частота из заголовка прошивки — или отказ.

    Три отдельные неприятности, которые раньше кончались одинаково плохо:
      — токена fs в заголовке нет (другая версия протокола, обрезанная
        строка): `float(fw.get("fs", 200.0))` молча подставлял 200 и ставил
        fs_source «заголовок прошивки», то есть запись получала ЛОЖНЫЙ штамп
        подтверждения прибором;
      — токен есть, но не число (`fs=abc` — один битый байт в порту, что
        предусмотрено декодированием с errors="replace"): неперехваченный
        ValueError с трассировкой;
      — токен есть и равен нулю: ZeroDivisionError уже ПОСЛЕ замера, когда
        десять минут данных лежат в файле с fs_hz=0 и replay отказывается их
        читать.
    Все три теперь трактуются как «заголовок частоту не назвал»: нужен
    --assume-fs, и запись честно помечается «задана вручную».
    """
    raw = fw.get("fs")
    if raw is not None:
        try:
            return check_fs_sane(float(raw), "fs в заголовке прошивки"), FS_KIND_NOMINAL
        except ValueError as exc:
            if assume_fs is None:
                raise SystemExit(
                    f"Заголовок прошивки пришёл с негодной частотой: fs={raw!r} "
                    f"({exc}).\nПисать файл с выдуманной частотой нельзя: все "
                    "числа будут неверны пропорционально, и это незаметно.\n"
                    "Если частота точно известна — задайте её явно: "
                    "--assume-fs 200"
                )
            return check_fs_sane(assume_fs, "--assume-fs"), FS_KIND_ASSUMED

    if assume_fs is None:
        raise SystemExit(
            "В заголовке прошивки нет токена fs — это другая версия протокола "
            "или обрезанная строка.\nПодставить 200 Гц молча нельзя: запись "
            "получила бы ложный штамп «частоту подтвердил прибор», и дальше "
            "этого не отличить ни по файлу, ни по отчёту.\n"
            "Задайте частоту явно и осознанно: --assume-fs 200"
        )
    return check_fs_sane(assume_fs, "--assume-fs"), FS_KIND_ASSUMED


def fw_settle_s(fw: dict[str, str]) -> float:
    """Сколько прибор ждёт установления тракта, в секундах.

    По §2.4 доминирующая постоянная времени тракта 10.1 с, до 1 % нужно 46 с,
    и прошивка столько ждёт. Хосту это нужно, чтобы не спутать законное
    молчание прибора с обрывом провода и не начать отсчёт длительности записи
    раньше первого отсчёта.
    """
    raw = fw.get("settle_ms")
    if raw:
        try:
            ms = float(raw)
            if 0.0 <= ms < 600000.0:
                return ms / 1000.0
        except ValueError:
            pass
    return SETTLE_S_DEFAULT


def fw_fs_meas(line_fields: dict[str, str], decim_hint: float | None = None) -> tuple[float | None, float | None]:
    """ИЗМЕРЕННАЯ частота из строки "# stat" / "# end" / "# raw begin".

    Прошивка печатает fs_meas уже приведённой к той оси, по которой идут
    индексы (для потока — выходные 200 Гц, для сырого захвата — 4000 Гц), и
    fs_span_s — длину интервала без потерь, по которому она посчитана. Пока
    интервал короче 2 с, печатается fs_meas=nan: неверное число хуже
    отсутствующего, и поэтому "nan" здесь обязан превращаться в None, а не в
    float('nan'), который дальше тихо отравит все вычисления.
    """
    raw = line_fields.get("fs_meas")
    span = None
    try:
        span_raw = line_fields.get("fs_span_s")
        span = float(span_raw) if span_raw else None
    except ValueError:
        span = None
    if not raw:
        return None, span
    try:
        hz = float(raw)
    except ValueError:
        return None, span
    if hz != hz or hz <= 0.0:          # nan или бессмыслица
        return None, span
    if not (FS_SANE_MIN_HZ < hz < FS_SANE_MAX_HZ):
        return None, span
    return hz, span


class SilenceWatch:
    """Сторож тишины порта. Отдельный объект, потому что нужен и записи, и
    живому режиму: повторить логику в двух местах значит получить два разных
    поведения при одной и той же неисправности.

    УСТАНОВЛЕНИЕ ТРАКТА — ЗАКОННОЕ МОЛЧАНИЕ. Прошивка после команды 's' ждёт
    46 с (§2.4: τ = 10.1 с, до 1 % нужно 4.6 τ) и только потом отдаёт первый
    отсчёт. Без этой поправки сторож все 46 с кричал бы «прибор ничего не
    присылает, проверьте кабель» — то есть учил бы человека не читать свои
    сообщения именно в тот момент, когда они впервые появляются.
    """

    def __init__(self, settle_s: float = 0.0) -> None:
        self.last_data = time.monotonic()
        self.last_warn = 0.0
        self.warned = False
        # Пока идёт установление, молчание объясняется, а не осуждается.
        # Полминуты сверху — на разбег команды и на разницу часов.
        self.settle_until = time.monotonic() + settle_s + 5.0 if settle_s else 0.0
        self.settle_s = settle_s
        self.settle_said = 0.0

    def saw_data(self) -> None:
        self.last_data = time.monotonic()
        self.settle_until = 0.0
        if self.warned:
            print("  поток пошёл.", flush=True)
            self.warned = False

    def check(self) -> None:
        now = time.monotonic()
        quiet = now - self.last_data
        if quiet < SILENCE_WARN_S:
            return
        if self.settle_until and now < self.settle_until:
            # Раз в 10 с говорим, чего ждём и почему. Человек у стенда должен
            # знать, что 46 секунд тишины — это норма, а не поломка.
            if now - self.settle_said >= 10.0:
                self.settle_said = now
                left = self.settle_until - now
                print(
                    f"  идёт установление тракта: прибор молчит штатно, "
                    f"осталось около {left:.0f} с из {self.settle_s:.0f}.",
                    flush=True,
                )
                print(
                    "    Ждём потому, что постоянная времени тракта 10.1 с "
                    "(§2.4), и до 1 % нужно 46 с: записанный",
                    flush=True,
                )
                print(
                    "    раньше сигнал ехал бы вниз всю запись, и этот дрейф "
                    "попадает прямо в полосу дыхания.",
                    flush=True,
                )
            return
        if self.warned and now - self.last_warn < SILENCE_REPEAT_S:
            return
        self.last_warn = now
        self.warned = True
        print(
            f"  ТИШИНА {quiet:.0f} с: прибор ничего не присылает. Либо поток не "
            "запущен (команда 's' не дошла),",
            flush=True,
        )
        print(
            "    либо плата перезагрузилась, либо это не тот порт. Проверить "
            "можно в терминале порта командой '?'.",
            flush=True,
        )


class SerialReader:
    """Построчное чтение порта с разбором протокола прошивки."""

    def __init__(self, ser, echo: bool = False) -> None:
        self.ser = ser
        self._buf = bytearray()
        self.fw_header: dict[str, str] = {}
        self.fw_header_raw: str = ""
        self.last_stat: dict[str, str] = {}
        self.end_line: dict[str, str] = {}
        self.begin_line: dict[str, str] = {}
        self.raw_begin: dict[str, str] = {}
        self.service_lines: list[str] = []
        self.bad_lines = 0
        # Строки прошивки, которые НАДО показывать человеку по мере
        # поступления. Прошивка печатает в них и отказы («наводка выше
        # границы линейности»), и обратный отсчёт установления, и сообщения о
        # потерях — собирать их молча в список значит выбросить.
        self.echo = echo
        # Последняя ИЗМЕРЕННАЯ прибором частота и интервал её измерения.
        self.fs_meas: float | None = None
        self.fs_meas_span: float | None = None
        self.gap_lines = 0

    def poll(self) -> list[tuple[int, float]]:
        """Прочитать всё, что пришло. Возвращает разобранные отсчёты."""
        chunk = self.ser.read(4096)
        if chunk:
            self._buf.extend(chunk)
        samples: list[tuple[int, float]] = []
        while True:
            nl = self._buf.find(b"\n")
            if nl < 0:
                break
            raw = bytes(self._buf[:nl])
            del self._buf[: nl + 1]
            # errors='replace': в служебных строках прошивки есть кириллица,
            # а на старте порта в буфер попадает мусор от загрузчика.
            line = raw.decode("utf-8", errors="replace").strip("\r\n \t")
            if not line:
                continue
            if line.startswith("#"):
                self._service(line)
                continue
            parsed = self._data(line)
            if parsed is None:
                # Строка не начинается с '#' и не разбирается как отсчёт. На
                # старте это мусор загрузчика ESP32, в середине потока —
                # признак ошибок на проводе. Считаем, отчёт покажет.
                self.bad_lines += 1
            else:
                samples.append(parsed)
        return samples

    def _service(self, line: str) -> None:
        self.service_lines.append(line)
        body = line.lstrip("#").strip()
        if body.startswith("utro-stage1"):
            self.fw_header = parse_fw_header(body)
            self.fw_header_raw = body
        elif body.startswith("stat "):
            self.last_stat = parse_fw_header(body)
            self._take_fs_meas(self.last_stat)
        elif body.startswith("end "):
            self.end_line = parse_fw_header(body)
            self._take_fs_meas(self.end_line)
        elif body.startswith("begin "):
            self.begin_line = parse_fw_header(body)
        elif body.startswith("raw begin"):
            self.raw_begin = parse_fw_header(body)
            self._take_fs_meas(self.raw_begin)
        elif body.startswith("gap ") or body.startswith("raw gap"):
            self.gap_lines += 1
        if self.echo and self._worth_showing(body):
            print(f"  [прибор] {body}", flush=True)

    @staticmethod
    def _worth_showing(body: str) -> bool:
        """Что из служебных строк показывать сразу.

        Показываем то, что требует действия или объясняет происходящее:
        отказы, предупреждения, обратный отсчёт установления, разрывы. Не
        показываем поток строк "stat" — их место в итоговом отчёте, а каждые
        5 секунд одна и та же строка учит человека не читать вывод.
        """
        if body.startswith("stat "):
            return False
        for mark in ("ОТКАЗ", "ВНИМАНИЕ", "ОШИБКА", "err ", "settle", "gap ",
                     "begin ", "end ", "raw "):
            if mark in body:
                return True
        return False

    def _take_fs_meas(self, fields: dict[str, str]) -> None:
        hz, span = fw_fs_meas(fields)
        if hz is not None:
            self.fs_meas, self.fs_meas_span = hz, span

    @staticmethod
    def _data(line: str) -> tuple[int, float] | None:
        idx, sep, val = line.partition(",")
        if not sep:
            return None
        try:
            return int(idx), float(val)
        except ValueError:
            return None


def wait_for_header(reader: SerialReader, timeout_s: float = 3.0) -> list[tuple[int, float]]:
    """Попросить заголовок и подождать его. Без заголовка мы не знаем ни fs,
    ни версию прошивки, а писать файл с выдуманной частотой нельзя."""
    reader.ser.write(CMD_HEADER)
    reader.ser.flush()
    deadline = time.monotonic() + timeout_s
    spare: list[tuple[int, float]] = []
    while time.monotonic() < deadline:
        spare += reader.poll()
        if reader.fw_header:
            break
        time.sleep(0.05)
    return spare


