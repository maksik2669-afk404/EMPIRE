def iso8601(raw: str) -> str:
    """Тип argparse для --started-at. Опечатку в дате argparse отбивает за
    миллисекунду; раньше она убивала итоговый отчёт по уже отработанному
    живому сеансу, потому что проверялась в самом конце."""
    try:
        return datetime.fromisoformat(raw).isoformat(timespec="seconds")
    except ValueError:
        raise argparse.ArgumentTypeError(
            f"{raw!r}: ожидается ISO 8601, например 2026-10-04T22:10:00 или "
            "2026-10-04T22:10:00+03:00"
        )


def positive_float(raw: str) -> float:
    """Тип argparse для частот. Проверять их в argparse, а не в середине
    работы: `--assume-fs 0` раньше записывал все десять минут и падал
    ZeroDivisionError ПОСЛЕ замера, когда данные уже лежали в файле с
    fs_hz=0, который replay принципиально отказывается читать."""
    try:
        val = float(raw)
    except ValueError:
        raise argparse.ArgumentTypeError(f"{raw!r} не число")
    try:
        return check_fs_sane(val, "частота")
    except ValueError as exc:
        raise argparse.ArgumentTypeError(str(exc))


def resolve_started_at(args) -> tuple[str, str]:
    """Время старта замера.

    Передаётся аргументом, потому что часы хоста — не то же самое, что время
    замера: ноутбук мог быть разбужен из сна, часовой пояс не настроен, запись
    могла начаться по команде оператора раньше запуска скрипта. Если аргумент
    не задан, берём часы хоста, но ЗАПИСЫВАЕМ В ФАЙЛ, что это именно они.

    Формат проверяется ещё в argparse (тип iso8601), поэтому сюда негодная
    строка не доходит. Проверка оставлена и здесь: без неё опечатка в дате
    съедала итоговую сводку живого сеанса без --out — единственный вызов
    случался ПОСЛЕ окончания сеанса, перед отчётом.
    """
    raw = getattr(args, "started_at", None)
    if raw:
        return iso8601(raw), "аргумент --started-at"
    return (
        datetime.now().astimezone().isoformat(timespec="seconds"),
        "часы хоста (--started-at не задан)",
    )


def cmd_record(args) -> int:
    out_path = Path(args.out).expanduser()
    out_path.parent.mkdir(parents=True, exist_ok=True)

    # Время старта проверяется ДО открытия порта: опечатка в дате не должна
    # обнаруживаться после записи.
    resolve_started_at(args)

    ser = open_serial(args.port, args.baud)
    reader = SerialReader(ser, echo=True)
    try:
        spare = wait_for_header(reader)
        if reader.fw_header:
            fw = reader.fw_header
            fs, fs_kind = fw_header_fs(fw, args.assume_fs)
            print(f"Прошивка: {reader.fw_header_raw}")
            if fs_kind == FS_KIND_NOMINAL:
                print(
                    f"Частота {fs:g} Гц — НОМИНАЛ из заголовка. Измеренную "
                    "(fs_meas) прибор пришлёт в строках"
                )
                print(
                    "  '# stat' и '# end'; она попадёт в файл и будет "
                    "использована при разборе."
                )
        else:
            fw = {}
            if args.assume_fs is None:
                raise SystemExit(
                    "Прошивка не прислала заголовок за 3 с, частота дискретизации "
                    "неизвестна.\nПисать файл с выдуманной частотой нельзя: все "
                    "числа будут неверны пропорционально, и это незаметно.\n"
                    "Проверьте порт и скорость, либо задайте частоту явно и "
                    "осознанно: --assume-fs 200"
                )
            fs = check_fs_sane(args.assume_fs, "--assume-fs")
            fs_kind = FS_KIND_ASSUMED
            print(f"Заголовка нет. Частота принята равной {fs:g} Гц по --assume-fs.")

        settle_s = fw_settle_s(fw) if fw else 0.0
        if settle_s:
            print(
                f"Прибор ждёт установления тракта {settle_s:.0f} с и только "
                "потом отдаёт первый отсчёт."
            )
            print(
                "  Это не задержка связи: постоянная времени тракта 10.1 с "
                "(§2.4), до 1 % нужно 4.6 τ = 46 с."
            )
            print(
                "  Отсчёт длительности записи начнётся с первого пришедшего "
                "отсчёта, а не с команды."
            )

        meta = build_meta(
            args, fw, fs, fs_kind, source=f"{args.port} @ {args.baud}"
        )

        asm = StreamAssembler(fs=fs)
        rows_written = 0
        if not args.no_start:
            ser.reset_input_buffer()
            reader._buf.clear()
            spare = []
            ser.write(CMD_START)
            ser.flush()

        print(
            f"Пишу в {out_path}. "
            + (f"Длительность {args.seconds:g} с. " if args.seconds else "")
            + "Остановить — Ctrl+C."
        )
        # Отсчёт длительности начинается с ПЕРВОГО ОТСЧЁТА, а не с команды:
        # прибор сначала 46 с ждёт установления тракта (§2.4), и если считать
        # от команды, то из десятиминутного замера 46 с окажутся ожиданием, а
        # записанных данных будет на 9 минут 14 секунд — на полтора окна
        # меньше, чем человек просил.
        deadline: float | None = None
        last_report = time.monotonic()
        silence = SilenceWatch(settle_s=settle_s)
        interrupted = False

        with open(out_path, "w", encoding="utf-8", newline="") as fh:
            write_capture_header(fh, meta)
            writer = csv.writer(fh, lineterminator="\n")
            for idx, val in spare:
                asm.push(idx, val)
                writer.writerow([idx, fmt_value(val)])
                rows_written += 1
            try:
                while True:
                    batch = reader.poll()
                    if batch:
                        silence.saw_data()
                        if deadline is None and args.seconds:
                            deadline = time.monotonic() + args.seconds
                            print(
                                f"  поток пошёл, пишу {args.seconds:g} с.",
                                flush=True,
                            )
                    for idx, val in batch:
                        asm.push(idx, val)
                        writer.writerow([idx, fmt_value(val)])
                        rows_written += 1
                    silence.check()
                    now = time.monotonic()
                    if now - last_report >= 5.0:
                        last_report = now
                        lost = asm.stats.lost
                        warn = f", ПРОПУЩЕНО {lost}" if lost else ""
                        print(
                            f"  {rows_written} отсчётов "
                            f"({rows_written / fs:.0f} с){warn}",
                            flush=True,
                        )
                    if deadline is not None and now >= deadline:
                        break
                    if not reader.ser.in_waiting:
                        time.sleep(0.02)
            except KeyboardInterrupt:
                interrupted = True
                print("\nПрерывание, останавливаю поток.")

            # Остановить прибор и дочитать его прощальную строку "# end":
            # в ней счётчики потерь самой прошивки — независимая проверка
            # нашего разбора индексов.
            try:
                ser.write(CMD_STOP)
                ser.flush()
                tail_deadline = time.monotonic() + 1.0
                while time.monotonic() < tail_deadline:
                    for idx, val in reader.poll():
                        asm.push(idx, val)
                        writer.writerow([idx, fmt_value(val)])
                        rows_written += 1
                    if reader.end_line:
                        break
                    time.sleep(0.05)
            except Exception as exc:                       # pragma: no cover
                print(f"  (не удалось остановить поток штатно: {exc})")

            # Отложенные отсчёты применить до подсчёта итогов.
            asm.flush()
            # Хвостовые метаданные: их значение известно только сейчас.
            # Читатель собирает '#'-строки по всему файлу, не только сверху.
            asm.stats.bad_rows += reader.bad_lines
            fh.write(_meta_line("rows", rows_written))
            fh.write(_meta_line("host_lost_by_index", asm.stats.lost))
            fh.write(_meta_line("host_filled", asm.stats.filled))
            fh.write(_meta_line("host_breaks", asm.stats.breaks))
            fh.write(_meta_line("host_bad_lines", reader.bad_lines))
            fh.write(_meta_line("stopped_at", datetime.now().astimezone().isoformat(timespec="seconds")))
            fh.write(_meta_line("interrupted", "да" if interrupted else "нет"))
            for key, src in (("fw_end_lost", reader.end_line), ("fw_stat_lost", reader.last_stat)):
                if src.get("lost") is not None:
                    fh.write(_meta_line(key, src["lost"]))
            for key in ("lost_pool", "lost_tx", "lost_bad", "lost_warm", "ovf"):
                if reader.end_line.get(key) is not None:
                    fh.write(_meta_line(f"fw_end_{key}", reader.end_line[key]))
            # ИЗМЕРЕННАЯ ЧАСТОТА — главное, что добавилось в proto=2. В
            # заголовок её положить нельзя: заголовок пишется до записи, а
            # измерить частоту можно только по самой записи. Поэтому она
            # дописывается в хвост отдельным ключом, а не вторым fs_hz:
            # два разных fs_hz в одном файле — это вопрос «какой верен», и
            # read_capture на него отвечает отказом, а не догадкой.
            if reader.fs_meas is not None:
                fh.write(_meta_line("fw_fs_meas_hz", f"{reader.fs_meas:.4f}"))
                if reader.fs_meas_span is not None:
                    fh.write(
                        _meta_line("fw_fs_span_s", f"{reader.fs_meas_span:.1f}")
                    )
            else:
                fh.write(
                    _meta_line(
                        "fw_fs_meas_hz_note",
                        "прибор частоту не измерил (интервал без потерь короче "
                        "2 с или заголовок не пришёл)",
                    )
                )
    finally:
        try:
            ser.close()
        except Exception:                                   # pragma: no cover
            pass

    # Длительность считаем по ИЗМЕРЕННОЙ частоте, если прибор её назвал.
    fs_report = reader.fs_meas or fs
    print(
        f"Записано {rows_written} отсчётов ({rows_written / fs_report:.1f} с) "
        f"в {out_path}"
    )
    if reader.fs_meas is not None:
        drift = (reader.fs_meas / fs - 1.0) * 100.0 if fs else 0.0
        print(
            f"Прибор измерил частоту: {reader.fs_meas:.3f} Гц "
            f"(номинал {fs:g}, расхождение {drift:+.3f}%). Разбор пойдёт по "
            "измеренной."
        )
        if abs(drift) > 1.0:
            print(
                "  ВНИМАНИЕ: расхождение больше 1% — все частоты, посчитанные "
                "по номиналу, были бы смещены"
            )
            print(
                "  на столько же (при дыхании 15 это 0.15 вдоха/мин, при "
                "пульсе 60 — 0.6 уд/мин)."
            )
    else:
        print(
            "ВНИМАНИЕ: прибор не назвал измеренную частоту (нужен интервал без "
            "потерь не короче 2 с)."
        )
        print(
            f"  Разбор пойдёт по {fs:g} Гц, и это НЕ подтверждённая прибором "
            "величина."
        )
    if not args.analyze:
        # При --analyze тот же блок печатает разбор ниже; дважды незачем.
        win_n, _ = window_steps(args.window, args.step, fs_report)
        for line in gap_block(
            asm.stats, fs_report, len(asm.segments),
            len(asm.usable_segments(win_n)), args.window,
        ):
            print(line)

    if rows_written == 0:
        print(
            "Ни одного отсчёта. Прошивка молчит: проверьте, что поток запущен "
            "(команда 's'), и что это тот самый порт."
        )
        return 1

    if args.analyze:
        return cmd_replay(
            argparse.Namespace(
                file=str(out_path),
                window=args.window,
                step=args.step,
                fs=None,
                ref_resp=args.ref_resp,
                ref_hr=args.ref_hr,
                quiet_windows=args.quiet_windows,
            )
        )
    print(
        f"\nРазобрать: python3 {Path(__file__).name} replay {out_path} "
        "--ref-resp <вдохов/мин> --ref-hr <пульс с пальца>"
    )
    # НЕ код вердикта: анализа не было. Иначе `record ... && закупать` даёт
    # зелёный свет записи, которую никто не разбирал.
    return EXIT_DONE_NO_VERDICT


