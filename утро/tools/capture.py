def gap_block(
    stats: GapStats,
    fs: float,
    n_segments: int | None = None,
    n_usable: int | None = None,
    window_s: float = WINDOW_S_DEFAULT,
) -> list[str]:
    """Пропуски. Молчать о них нельзя, даже если их мало.

    Потерянный отсчёт не виден в данных: сигнал остаётся правдоподобным. Но
    если потерю просто выбросить, ось времени сжимается, и ВСЕ частоты
    завышаются ровно на долю потерь — 1% потерь это +0.15 вдоха/мин при
    дыхании 15 и +0.6 уд/мин при пульсе 60. Человек такого не заметит.
    Поэтому потери здесь не выбрасываются, а делятся на два вида, и
    остаточное влияние каждого названо явно.
    """
    L = ["ЦЕЛОСТНОСТЬ ПОТОКА"]
    L.append(
        f"  принято: {samples_nom(stats.rows)} "
        f"({stats.rows / fs:.1f} с при {fs:g} Гц)"
    )
    if stats.bad_rows:
        L.append(
            f"  строк не разобрано: {stats.bad_rows} — мусор в порту "
            "(дребезг при подключении) или обрезанный файл"
        )
    if stats.odd_index:
        L.append(
            f"  строк с неправдоподобным индексом: {stats.odd_index} — "
            "выброшены как мусор в порту"
        )
        L.append(
            "    (индекс не вырос, но следующие строки продолжили прежнюю "
            "последовательность: значит"
        )
        L.append(
            "    потеряна цифра в одной строке, а не перезапущен поток. "
            "Потери на это НЕ начислены,"
        )
        L.append("    запись не разрезана)")
    if stats.restarts:
        L.append(
            f"  поток перезапускали {stats.restarts} "
            f"{plural(stats.restarts, 'раз', 'раза', 'раз')} (индекс пошёл с "
            "нуля — команда 's'): в этих местах"
        )
        L.append(
            "    запись разрезана, окна через стык не строятся. Длина паузы "
            "между отрезками неизвестна."
        )

    if stats.lost == 0:
        L.append("  ПРОПУСКОВ НЕТ — ось времени целая, частоты не смещены")
    else:
        pct = stats.lost_fraction * 100.0
        L.append(
            f"  ПРОПУЩЕНО {samples_nom(stats.lost)} из ожидаемых "
            f"{stats.expected} ({pct:.3f}%), это {stats.lost / fs:.2f} с"
        )
        L.append("  ПРОПУСКИ ИСКАЖАЮТ ОЦЕНКУ ЧАСТОТЫ. Что с ними сделано:")
        if stats.filled:
            L.append(
                f"    {samples_nom(stats.filled)} в коротких пропусках (до "
                f"{GAP_FILL_MAX_SAMPLES} отсчётов = "
                f"{GAP_FILL_MAX_SAMPLES / fs * 1000:.0f} мс) восстановлены"
            )
            L.append(
                "      линейной вставкой: ось времени сохранена, частоты НЕ "
                "смещены, но на длине вставки"
            )
            L.append(
                "      сигнала нет — в кардиополосе это дырка, то есть "
                "уверенность по пульсу занижена,"
            )
            L.append("      а не завышена.")
        if stats.lost_split:
            L.append(
                f"    {samples_nom(stats.lost_split)} в {stats.breaks} "
                + plural(
                    stats.breaks,
                    "длинном пропуске",
                    "длинных пропусках",
                    "длинных пропусках",
                )
                + " не восстановлены вовсе:"
            )
            L.append(
                "      запись на них РАЗРЕЗАНА, окна через стык не строятся. "
                "Это дороже по времени"
            )
            L.append(
                "      наблюдения, зато вставка длиной в секунды не попадает в "
                "полосу дыхания"
            )
            L.append("      0.08-0.7 Гц и не читается как вдох.")
        if pct > 1.0:
            L.append(
                "    ПОТЕРЬ БОЛЬШЕ 1% — записи верить нельзя, даже с оговорками "
                "выше. Снизьте"
            )
            L.append(
                "    скорость порта до 115200 (UTRO_SERIAL_BAUD в прошивке), "
                "смените USB-кабель,"
            )
            L.append("    повторите замер.")

    if stats.lost_unknown:
        L.append(
            f"  РАЗРЫВЫ НЕИЗВЕСТНОЙ ДЛИНЫ: {stats.unknown_breaks} "
            + plural(stats.unknown_breaks, "штука", "штуки", "штук")
            + f", по индексам не хватает {samples_nom(stats.lost_unknown)}"
        )
        L.append(
            "    Это больше 10 с подряд: либо прибор отсутствовал столько "
            "времени, либо индекс пришёл"
        )
        L.append(
            "    испорченным. В долю потерь выше это НЕ включено — длина "
            "пропуска здесь и есть"
        )
        L.append(
            "    неизвестная величина, а посчитанная доля выглядела бы "
            "достовернее, чем она есть."
        )
        L.append("    Запись в этих местах разрезана.")

    if n_segments is not None and n_segments > 1:
        # Цена разрезания должна быть видна: человек записал 10 минут, а окон
        # получил не 19, а меньше. Много отрезков и мало годных — это отказ
        # порта, а не свойство матраса, и перепутать эти две вещи легко.
        L.append(
            f"  запись распалась на {n_segments} непрерывных "
            f"{plural(n_segments, 'отрезок', 'отрезка', 'отрезков')}; "
            f"полные окна по {window_s:g} с набрались в "
            f"{n_usable if n_usable is not None else 0} из них"
        )
        if not n_usable:
            L.append(
                f"    Ни один отрезок не дотянул до {window_s:g} с. Это отказ "
                "порта или кабеля, а не свойство матраса."
            )
    return L


def totals_block(
    totals: Totals,
    window_s: float = WINDOW_S_DEFAULT,
    step_s: float = STEP_S_DEFAULT,
) -> list[str]:
    L = ["ИТОГ ПО ОКНАМ"]
    L.append(
        f"  зачтено {windows_nom(totals.counted)}"
        + (f", отброшено по вставкам: {totals.rejected}" if totals.rejected else "")
    )
    if totals.counted == 0:
        # При нуле окон этот блок раньше всё равно печатал «найден в 0 окнах
        # из 0 (0%) — ЭТО ОТВЕТ ЭТАПА 1», то есть читался как приговор матрасу
        # там, где данных нет вовсе. Ровно это разделение (нет данных против
        # нет пульса) инструмент и обязан держать.
        L.append("  окон, зачтённых к вердикту, нет — смотрите вердикт ниже")
        return L
    if step_s > window_s:
        # Шаг больше окна — часть записи не попадает ни в одно окно, и доля
        # окон считается по выборке, а не по всей записи.
        skipped = (step_s - window_s) / step_s
        L.append(
            f"  ВНИМАНИЕ: шаг ({step_s:g} с) больше окна ({window_s:g} с) — "
            f"{skipped * 100:.0f}% записи не попало"
        )
        L.append(
            "    ни в одно окно и не анализировалось вовсе. Доля окон ниже "
            "посчитана по выборке, а не"
        )
        L.append(
            "    по всей записи, и с долей при настройках по умолчанию "
            "несравнима."
        )
    if step_s < window_s:
        # Перекрытие названо явно: без этой строки «100% окон» читается
        # как «100 независимых подтверждений», чем оно не является.
        L.append(
            f"  ВАЖНО: окна перекрываются ({window_s:g} с с шагом {step_s:g} с), "
            f"соседние делят "
            f"{(1.0 - step_s / window_s) * 100:.0f}% данных —"
        )
        L.append(
            "    доля окон это не доля независимых испытаний, а мера "
            "устойчивости результата."
        )
    rm = totals.resp_median
    hm = totals.hr_median
    L.append(
        f"  дыхание: медиана {rm:.1f}/мин" if rm is not None
        else "  дыхание: не определилось ни разу"
    )
    if rm is not None:
        L.append(
            f"    найдено в {windows_prep(totals.resp_found)} из "
            f"{totals.counted} ({totals.resp_fraction * 100:.0f}%)"
        )
        if len(totals.resp_values) > 1:
            L.append(
                f"    разброс: {min(totals.resp_values):.1f}…"
                f"{max(totals.resp_values):.1f}/мин"
            )
    L.append(
        f"  пульс: медиана {hm:.1f} уд/мин" if hm is not None
        else "  пульс: не определился ни разу"
    )
    L.append(
        f"    найден в {windows_prep(totals.hr_found)} из {totals.counted} "
        f"({totals.hr_fraction * 100:.0f}%) — ЭТО ОТВЕТ ЭТАПА 1"
    )
    if hm is not None and len(totals.hr_values) > 1:
        L.append(
            f"    разброс: {min(totals.hr_values):.1f}…{max(totals.hr_values):.1f} уд/мин"
        )
    L.append(
        f"    окон, где пульс вообще искался (один человек, без шевеления): "
        f"{totals.hr_eligible}"
    )
    if totals.hr_eligible:
        L.append(
            f"      из них пульс найден в {totals.hr_found_eligible} "
            f"({totals.hr_fraction_eligible * 100:.0f}%) — это диагностика, "
            "вердикт считается по всем окнам"
        )
    L.append(
        f"  занято: {windows_nom(totals.occupied)}, "
        f"шевеление: {windows_nom(totals.motion)}"
    )
    return L


def full_report(
    reports: list[WindowReport],
    stats: GapStats,
    fs_info: FsInfo,
    meta: dict[str, str],
    ref_resp: float | None,
    ref_hr: float | None,
    quiet_windows: bool = False,
    window_s: float = WINDOW_S_DEFAULT,
    step_s: float = STEP_S_DEFAULT,
    n_segments: int | None = None,
    n_usable: int | None = None,
    levels: LevelStats | None = None,
) -> int:
    fs = fs_info.hz
    out: list[str] = []
    out.append("")
    out.append("=" * 72)
    out.append("ПРОВЕРОЧНЫЙ СТЕНД «УТРО», ЭТАП 1 — РАЗБОР ЗАПИСИ")
    out.append("=" * 72)
    src = meta.get("source", "—")
    out.append(
        f"  начало записи: {meta.get('started_at', '—')} "
        f"(источник времени: {meta.get('started_at_source', '—')})"
    )
    out.append(
        f"  прошивка: {meta.get('fw_version', '—')}, протокол "
        f"{meta.get('fw_proto', '—')}, "
        f"разрядность {meta.get('bits', '—')}, "
        f"сумма по {meta.get('oversample', '—')} сырым отсчётам"
    )
    out.append(f"  источник: {src}")
    if meta.get("note"):
        out.append(f"  пометка: {meta['note']}")
    # Частота и её происхождение — отдельными строками и всегда. Это не
    # косметика: строка «fs=250 Гц» в одном ряду с версией прошивки читается
    # как показание прибора, даже когда 250 пришло из командной строки и
    # противоречит файлу.
    nominal = None
    try:
        nominal = float(meta["fs_hz"]) if meta.get("fs_hz") else None
    except ValueError:
        nominal = None
    out += fs_info.header_lines(nominal if fs_info.confirmed else None)
    out.append("")
    out += gap_block(stats, fs, n_segments, n_usable, window_s)

    # Счётчики потерь самой прошивки, если они попали в файл: независимая
    # проверка нашего разбора индексов. Расхождение значит, что потеря
    # произошла на хосте (переполнение буфера драйвера USB), а не в приборе.
    fw_lost = meta.get("fw_end_lost") or meta.get("fw_stat_lost")
    if fw_lost is not None:
        out.append(f"  прошивка сама насчитала потерь: {fw_lost}")
        try:
            if int(fw_lost) != stats.lost:
                out.append(
                    "    РАСХОЖДЕНИЕ с нашим разбором индексов: разница — это "
                    "потери на стороне хоста (буфер USB/порта), прибор о них "
                    "не знает."
                )
        except ValueError:
            pass

    level_lines = levels_block(levels)
    if level_lines:
        out.append("")
        out += level_lines

    out.append("")
    if not quiet_windows:
        out.append(f"ОКНА ({window_s:g} с, шаг {step_s:g} с)")
        if not reports:
            out.append("  нет ни одного полного окна")
        for rep in reports:
            out.append("  " + format_window_line(rep))
        out.append("")

    totals = summarize(reports)
    out += totals_block(totals, window_s, step_s)
    out.append("")
    ref_lines, ref = reference_block(totals, ref_resp, ref_hr)
    out += ref_lines
    code, verdict_lines = verdict(
        totals,
        ref,
        gaps=stats,
        levels=levels,
        fs_info=fs_info,
        window_s=window_s,
        step_s=step_s,
    )
    out += verdict_lines
    out.append("=" * 72)

    print("\n".join(out))
    return code


