def cmd_replay(args) -> int:
    path = Path(args.file).expanduser()
    if not path.exists():
        raise SystemExit(f"Файла нет: {path}")
    check_window_args(args.window, args.step)
    try:
        meta, rows, comments, bad_rows = read_capture(path)
        fs_info = resolve_fs(meta, args.fs)
    except ValueError as exc:
        raise SystemExit(str(exc))
    fs = fs_info.hz

    if not rows:
        raise SystemExit(
            f"{path}: нет ни одной строки данных. В файле только метаданные — "
            "запись не состоялась (прибор молчал) или файл обрезан."
        )

    # Файл сырого потока 4000 Гц сюда попадать не должен: analyze_window
    # рассчитан на выходной поток, а главное — у сырого потока другая ось и
    # другой смысл значения. Проверка по оси, а не по имени файла.
    if fs >= RAW_RATE_MIN_HZ:
        raise SystemExit(
            f"{path}: частота {fs:g} Гц — это сырой поток АЦП, а не выходной "
            f"поток {FS_EXPECTED_HZ:g} Гц.\nДыхание и пульс по нему этот режим "
            "не считает. Для проверки наводки 50 Гц по сырому потоку есть "
            f"режим mains:\n    python3 {Path(__file__).name} mains {path}"
        )

    asm = StreamAssembler(fs=fs)
    for idx, val in rows:
        asm.push(idx, val)
    asm.flush()
    asm.stats.bad_rows += bad_rows

    # Уровень сигнала считается по ПРИНЯТЫМ отсчётам, а не по отрезкам: нас
    # интересует, что отдавал тракт, и вставленные интерполяцией значения в
    # этом вопросе ничего не говорят.
    levels = level_stats([v for _, v in rows], meta)

    win_n, _ = window_steps(args.window, args.step, fs)
    segments = asm.usable_segments(win_n)
    reports = analyze_segments(segments, fs, args.window, args.step)

    # Эталон из файла, если в командной строке не задан: запись могла быть
    # сделана с --ref-resp/--ref-hr, и терять их при разборе глупо.
    ref_resp = args.ref_resp
    ref_hr = args.ref_hr
    if ref_resp is None and meta.get("ref_resp_bpm"):
        try:
            ref_resp = float(meta["ref_resp_bpm"])
        except ValueError:
            pass
    if ref_hr is None and meta.get("ref_hr_bpm"):
        try:
            ref_hr = float(meta["ref_hr_bpm"])
        except ValueError:
            pass

    for c in comments:
        print(f"# {c}")

    return full_report(
        reports, asm.stats, fs_info, meta, ref_resp, ref_hr,
        quiet_windows=getattr(args, "quiet_windows", False),
        window_s=args.window,
        step_s=args.step,
        n_segments=len(asm.segments),
        n_usable=len(segments),
        levels=levels,
    )


