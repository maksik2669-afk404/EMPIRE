# ПОЧЕМУ ЭТО НЕЛЬЗЯ СДЕЛАТЬ ПО ПОТОКУ 200 Гц. Скользящая сумма по 80 сырым
# отсчётам — это окно ровно 20.000 мс, то есть ровно период сети, и её
# гребёнка ставит ТОЧНЫЙ НУЛЬ на 50 Гц (и на 100, и на 150). Наводка
# уничтожается ДО прореживания, поэтому в выходном потоке информации о ней не
# остаётся вовсе: любая оценка 50 Гц по потоку 200 Гц структурно равна нулю, а
# «компенсация усреднения» делением на коэффициент гребёнки — это деление на
# нуль. Отсюда и сырой режим в прошивке, и этот режим здесь.


@dataclass
class MainsResult:
    """Результат измерения наводки 50 Гц в кодах АЦП."""

    fs: float
    fs_confirmed: bool
    n: int
    amp50: float
    rms: float
    pp: float
    at_hz: float
    amp100: float
    amp150: float
    gaps: int
    index_jumps: int
    clip_lo: int
    clip_hi: int
    scale: float

    @property
    def frac(self) -> float:
        """Доля наводки от размаха RMS*sqrt(2) — признак «наводка
        доминирует» из §6.7."""
        denom = self.rms * math.sqrt(2.0)
        return self.amp50 / denom if denom > 0 else 0.0


def read_mains_source(path: Path) -> tuple[list[float], dict[str, str], dict[str, str], int, int]:
    """Прочитать файл сырого потока: выгрузку команды 'r' ИЛИ CSV capture.py.

    Возвращает (коды одного отсчёта АЦП, метаданные, поля '# raw begin',
    число строк о разрывах, число разрывов по индексам).
    Разбор сделан ровно по процедуре §6.7 п.4, включая деление на scale: в
    выгрузке 'r' значение — код ОДНОГО отсчёта АЦП (0..4095), а в CSV
    capture.py — сумма sum_len отсчётов, и сравнивать её с порогами в кодах
    нельзя без деления.
    """
    meta: dict[str, str] = {}
    raw_begin: dict[str, str] = {}
    gaps = 0
    values: list[float] = []
    indices: list[int] = []

    with open(path, "r", encoding="utf-8", errors="replace") as fh:
        for line in fh:
            t = line.lstrip()
            if t.startswith("#"):
                body = t.lstrip("#").strip()
                if body.startswith("raw begin"):
                    raw_begin = parse_fw_header(body)
                elif body.startswith("raw start"):
                    raw_begin.setdefault("fs_nom", parse_fw_header(body).get("fs_nom", ""))
                elif body.startswith("raw gap") or body.startswith("gap "):
                    gaps += 1
                elif body.startswith("utro-stage1"):
                    meta.setdefault("fw_header", body)
                elif "=" in body:
                    # Отдельная строка метаданных "# ключ=значение" — так
                    # пишет capture.py. Токены ВНУТРИ строк прошивки сюда не
                    # попадают: они разобраны ветками выше.
                    k, v = body.split("=", 1)
                    k = k.strip()
                    if k and " " not in k:
                        meta[k] = v.strip()
                continue
            t = t.strip()
            if not t or not t[0].isdigit():
                # Эхо команд, мусор загрузчика, строка имён колонок.
                continue
            parts = t.split(",")
            if len(parts) < 2:
                continue
            try:
                idx = int(parts[0])
                val = float(parts[1])
            except ValueError:
                continue
            indices.append(idx)
            values.append(val)

    # Независимая проверка разрывов по самим индексам: прошивка печатает
    # '# raw gap' только для первых UTRO_RAW_GAPS разрывов, а пропуск сдвигает
    # фазу и ЗАНИЖАЕТ оценку наводки — то есть делает её безопасной на вид.
    index_jumps = sum(
        1 for a, b in zip(indices, indices[1:]) if b - a != 1
    )
    return values, meta, raw_begin, gaps, index_jumps


def measure_mains(path: Path, fs_override: float | None) -> MainsResult:
    values, meta, raw_begin, gaps, index_jumps = read_mains_source(path)
    if len(values) < 100:
        raise SystemExit(
            f"{path}: в файле {len(values)} строк данных — для оценки наводки "
            "нужен хотя бы заметный кусок записи. Это точно файл сырого "
            "потока (выгрузка команды 'r')?"
        )

    # Частота: ТОЛЬКО измеренная или явно заданная. Номинал 4000 Гц здесь не
    # годится: расхождение частоты сдвигает оценку 50 Гц по склону пика, то
    # есть занижает её — ошибку в безопасную сторону, которую не видно.
    fs: float | None = None
    fs_confirmed = False
    if fs_override is not None:
        fs = check_fs_sane(fs_override, "--fs")
    else:
        hz, _span = fw_fs_meas(raw_begin)
        if hz is not None:
            fs, fs_confirmed = hz, True
        else:
            hz2, _ = fw_fs_meas({"fs_meas": meta.get("fw_fs_meas_hz", "")})
            if hz2 is not None:
                fs, fs_confirmed = hz2, True
            elif meta.get("fs_hz"):
                try:
                    fs = check_fs_sane(float(meta["fs_hz"]), "fs_hz в файле")
                except ValueError:
                    fs = None
    if fs is None:
        raise SystemExit(
            f"{path}: частота неизвестна — нет ни fs_meas в строке "
            "'# raw begin', ни fs_hz в метаданных (или fs_meas=nan: прибор не "
            "смог её измерить за интервал без потерь).\nСчитать наводку не по "
            "той частоте нельзя: оценка уедет по склону пика ВНИЗ, то есть "
            "наводка покажется меньше, чем она есть.\nПовторите захват "
            "подольше ('r 10') или задайте частоту явно: --fs 4000"
        )

    if fs < RAW_RATE_MIN_HZ:
        raise SystemExit(
            f"{path}: частота {fs:g} Гц — это ВЫХОДНОЙ поток, а не сырой.\n"
            "По нему наводку 50 Гц измерить невозможно: скользящая сумма по 80 "
            "отсчётам (окно 20.000 мс = период\nсети) ставит на 50 Гц точный "
            "нуль, и любая оценка по такому потоку структурно равна нулю — "
            "включая\nобнадёживающий ответ «наводки нет».\nНужен сырой поток "
            f"{RAW_RATE_EXPECTED_HZ:g} Гц: команда прошивки 'r 10' (см. режим "
            "raw этого инструмента или §6.7 п.2)."
        )

    # Масштаб: в CSV capture.py значение — сумма sum_len отсчётов, пороги же
    # заданы в кодах ОДНОГО отсчёта АЦП.
    scale = 1.0
    if meta.get("scale"):
        try:
            scale = float(meta["scale"]) or 1.0
        except ValueError:
            scale = 1.0
    codes = [v / scale for v in values]

    # Клиппинг сырых кодов: если тракт упёрт в шину, оценка наводки
    # бессмысленна — срез сам рождает гармоники.
    clip_lo = sum(1 for v in codes if v <= 0.5)
    clip_hi = sum(1 for v in codes if v >= 4094.5)

    dc = sum(codes) / len(codes)
    centred = [v - dc for v in codes]
    # ВАЖНО: dsp.goertzel возвращает модуль ДПФ, делённый на длину окна, то
    # есть для синусоиды амплитудой A даёт A/2. Отсюда множитель 2 — он не
    # «на всякий случай», он проверен подстановкой синусоиды известной
    # амплитуды (см. §6.7 п.4 и проверку в этом файле на синтетике).
    amp50 = 2.0 * goertzel(centred, fs, MAINS_HZ)
    amp100 = 2.0 * goertzel(centred, fs, 2 * MAINS_HZ)
    amp150 = 2.0 * goertzel(centred, fs, 3 * MAINS_HZ)
    rms = math.sqrt(sum(v * v for v in centred) / len(centred))
    pp = max(centred) - min(centred)

    # Где на самом деле стоит пик: сеть не ровно 50.000 Гц, а если пик уехал
    # далеко — считали не наводку. Шаг 0.1 Гц: при записи 10 с спектральное
    # разрешение 0.1 Гц, мельче смысла нет.
    best_hz, best_amp = MAINS_HZ, amp50
    f = MAINS_HZ - 1.0
    while f <= MAINS_HZ + 1.0 + 1e-9:
        a = 2.0 * goertzel(centred, fs, f)
        if a > best_amp:
            best_hz, best_amp = f, a
        f += 0.1

    return MainsResult(
        fs=fs, fs_confirmed=fs_confirmed, n=len(codes), amp50=amp50, rms=rms,
        pp=pp, at_hz=best_hz, amp100=amp100, amp150=amp150, gaps=gaps,
        index_jumps=index_jumps, clip_lo=clip_lo, clip_hi=clip_hi, scale=scale,
    )


def cmd_mains(args) -> int:
    path = Path(args.file).expanduser()
    if not path.exists():
        raise SystemExit(f"Файла нет: {path}")
    r = measure_mains(path, args.fs)

    out: list[str] = ["", "=" * 72]
    out.append("НАВОДКА 50 Гц ПО СЫРОМУ ПОТОКУ — проверка §6.7")
    out.append("=" * 72)
    out.append(f"  файл: {path}")
    out.append(
        f"  отсчётов: {r.n} ({r.n / r.fs:.2f} с при {r.fs:g} Гц)"
        + ("" if r.scale == 1.0 else f", значения делены на scale={r.scale:g}")
    )
    out.append(
        f"  частота: {r.fs:.3f} Гц — "
        + (
            "измеренная прибором (fs_meas)"
            if r.fs_confirmed
            else "НЕ подтверждена прибором"
        )
    )
    if not r.fs_confirmed:
        out.append(
            "    Оценка 50 Гц по неверной частоте уезжает по склону пика ВНИЗ: "
            "наводка покажется меньше,"
        )
        out.append(
            "    чем она есть. Это ошибка в опасную сторону — повторите захват "
            "и возьмите fs_meas."
        )
    out.append("")
    out.append(f"  амплитуда 50 Гц: {r.amp50:.1f} кодов АЦП")
    out.append(f"  RMS записи:      {r.rms:.1f} кодов")
    out.append(f"  размах p-p:      {r.pp:.1f} кодов")
    out.append(
        f"  доля наводки:    {r.frac:.2f} (амплитуда 50 Гц / (RMS*sqrt(2)); "
        f"порог §6.7 — {MAINS_FRAC_MAX:.1f})"
    )
    out.append(
        f"  пик в полосе 49…51 Гц стоит на {r.at_hz:.1f} Гц "
        + (
            "— это сеть"
            if abs(r.at_hz - MAINS_HZ) <= 0.5
            else "— далеко от 50.0, считали, возможно, не наводку"
        )
    )
    out.append(
        f"  гармоники: 100 Гц {r.amp100:.1f}, 150 Гц {r.amp150:.1f} кодов "
        "(растут при ограничении в тракте)"
    )

    problems: list[str] = []
    if r.gaps or r.index_jumps:
        out.append("")
        out.append(
            f"  РАЗРЫВЫ В ЗАХВАТЕ: строк '# raw gap' — {r.gaps}, скачков "
            f"индекса — {r.index_jumps}."
        )
        out.append(
            "    Пропуск сдвигает фазу и ЗАНИЖАЕТ оценку наводки. По §6.7 "
            "такой кусок негоден: повторите 'r 10'."
        )
        problems.append("разрывы")
    if r.clip_lo or r.clip_hi:
        out.append("")
        out.append(
            f"  КЛИППИНГ СЫРЫХ КОДОВ: у нуля {r.clip_lo}, у 4095 {r.clip_hi} "
            f"отсчётов из {r.n}."
        )
        out.append(
            "    Срез сам рождает гармоники, и оценка наводки по такой записи "
            "ничего не значит. Уменьшите G (§6.6)."
        )
        problems.append("клиппинг")

    out.append("")
    out.append("ВЕРДИКТ ПО НАВОДКЕ (пороги §6.7 п.3, в кодах АЦП)")
    stop = r.amp50 > MAINS_AMP_STOP_LSB or r.pp > MAINS_PP_STOP_LSB
    edge = r.amp50 > MAINS_AMP_GOOD_LSB or r.pp > MAINS_PP_GOOD_LSB
    if problems:
        out.append(
            "  ИЗМЕРЕНИЕ НЕ ГОДИТСЯ: " + ", ".join(problems) + "."
        )
        out.append(
            "  Числа выше занижены или бессмысленны, вердикта по наводке нет. "
            "Устраните и повторите."
        )
        code = EXIT_NO_VERDICT
    elif stop:
        out.append(
            f"  СТОП. Наводка {r.amp50:.1f} кодов амплитуды (порог "
            f"{MAINS_AMP_STOP_LSB:.0f}), размах {r.pp:.1f} (порог "
            f"{MAINS_PP_STOP_LSB:.0f})."
        )
        out.append(
            "  Это ГРАНИЦА ЛИНЕЙНОСТИ: 300 мВ бюджета на выходе каскада 2 "
            "(§2.3) АЦП видит через H2(50)=0.550,"
        )
        out.append(
            "  то есть 165 мВ = 218 кодов. Дальше каскад ограничивает, а "
            "ограничение рождает гармоники прямо"
        )
        out.append(
            "  в полосе пульса 4-20 Гц — то есть ЛОЖНЫЙ пульс, который ни "
            "гребёнка, ни dsp.py не уберут."
        )
        out.append("  Чинить МЕХАНИКУ по §4.1, по убыванию действенности:")
        out.append("    1. экран плёнки (§4.1 п.1);")
        out.append("    2. питание от повербанка, ноутбук на батарее (п.5);")
        out.append("    3. укоротить и закрепить кабель плёнки (п.3);")
        out.append("    4. разнести от сетевой проводки (п.4).")
        out.append(
            "  Усиление НЕ уменьшать: допуск по наводке на входе "
            "масштабируется как 1/G, а не наоборот."
        )
        out.append("  После каждой меры — перезамер этим же режимом.")
        code = EXIT_MAINS_BAD
    elif edge:
        out.append(
            f"  НА ПРЕДЕЛЕ. Наводка {r.amp50:.1f} кодов (хорошо — до "
            f"{MAINS_AMP_GOOD_LSB:.0f}), размах {r.pp:.1f} (хорошо — до "
            f"{MAINS_PP_GOOD_LSB:.0f})."
        )
        out.append(
            "  Запас к границе линейности меньше двух раз. Писать можно, но "
            "сначала пройдите меры §4.1:"
        )
        out.append(
            "  экран плёнки, питание от повербанка, короткий кабель. Это "
            "дешевле, чем переделывать замер."
        )
        code = EXIT_MAINS_BAD
    else:
        out.append(
            f"  ХОРОШО. Наводка {r.amp50:.1f} кодов амплитуды (порог "
            f"{MAINS_AMP_GOOD_LSB:.0f}), размах {r.pp:.1f} (порог "
            f"{MAINS_PP_GOOD_LSB:.0f})."
        )
        out.append(
            "  Запас к границе линейности больше двух раз. Можно писать замер "
            "(§6.8)."
        )
        if r.frac > MAINS_FRAC_MAX:
            out.append(
                f"  Примечание: доля наводки {r.frac:.2f} выше "
                f"{MAINS_FRAC_MAX:.1f} — наводка хоть и мала, но в этой записи"
            )
            out.append(
                "  она главное, что есть. При пустой постели это нормально: "
                "кроме неё и шума АЦП там нечему быть."
            )
        code = EXIT_PULSE_OK
    out.append("=" * 72)
    print("\n".join(out))
    return code


