def open_serial(port: str, baud: int):
    """Ленивый импорт pyserial.

    Импорт именно здесь, а не наверху файла: режим replay — работа с уже
    записанным файлом — обязан работать на машине, где pyserial не стоит
    (например, когда запись привезли на другой компьютер). Наверху импорт
    уронил бы и replay.
    """
    try:
        import serial  # type: ignore
    except ImportError:
        raise SystemExit(
            "Для работы с портом нужен pyserial, его нет.\n"
            "  python3 -m pip install pyserial\n"
            "  (в Debian/Ubuntu: sudo apt install python3-serial)\n"
            "Разбор уже записанного файла (режим replay) работает и без него."
        )

    try:
        from serial.tools import list_ports  # type: ignore
    except ImportError:
        list_ports = None

    try:
        # timeout=0.2 — не блокируемся навсегда: нужно успевать реагировать на
        # Ctrl+C и на таймер длительности записи.
        return serial.Serial(port, baud, timeout=0.2)
    except Exception as exc:
        msg = [f"Не удалось открыть порт {port} на {baud} бод: {exc}"]
        if list_ports is not None:
            found = [f"{p.device} — {p.description}" for p in list_ports.comports()]
            if found:
                msg.append("Доступные порты:")
                msg += ["  " + f for f in found]
            else:
                msg.append(
                    "Портов не видно вообще. Проверьте кабель (бывают "
                    "зарядные без данных) и права: обычно нужна группа "
                    "dialout/uucp."
                )
        raise SystemExit("\n".join(msg))


def parse_fw_header(line: str) -> dict[str, str]:
    """Разобрать строку-заголовок прошивки.

    # utro-stage1 fw=1.0.0 proto=1 fs=200 oversample=32 raw_fs=6400 bits=12
    #   scale=32 vmin=0 vmax=131040 gpio=4 adc=1 ch=3 atten_db=12
    #   fmt=index,sum baud=460800
    """
    out: dict[str, str] = {}
    for token in line.split():
        if "=" in token:
            k, v = token.split("=", 1)
            out[k] = v
    return out


class SilenceWatch:
    """Сторож тишины порта. Отдельный объект, потому что нужен и записи, и
    живому режиму: повторить логику в двух местах значит получить два разных
    поведения при одной и той же неисправности."""

    def __init__(self) -> None:
        self.last_data = time.monotonic()
        self.last_warn = 0.0
        self.warned = False

    def saw_data(self) -> None:
        self.last_data = time.monotonic()
        if self.warned:
            print("  поток пошёл.", flush=True)
            self.warned = False

    def check(self) -> None:
        now = time.monotonic()
        quiet = now - self.last_data
        if quiet < SILENCE_WARN_S:
            return
        if self.warned and now - self.last_warn < SILENCE_REPEAT_S:
            return
        self.last_warn = now
        self.warned = True
        print(
            f"  ТИШИНА {quiet:.0f} с: прибор ничего не присылает. Либо поток не "
            "запущен (команда 's' не дошла),",
            flush=True,
        )
        print(
            "    либо плата перезагрузилась, либо это не тот порт. Проверить "
            "можно в терминале порта командой '?'.",
            flush=True,
        )


class SerialReader:
    """Построчное чтение порта с разбором протокола прошивки."""

    def __init__(self, ser) -> None:
        self.ser = ser
        self._buf = bytearray()
        self.fw_header: dict[str, str] = {}
        self.fw_header_raw: str = ""
        self.last_stat: dict[str, str] = {}
        self.end_line: dict[str, str] = {}
        self.service_lines: list[str] = []
        self.bad_lines = 0

    def poll(self) -> list[tuple[int, float]]:
        """Прочитать всё, что пришло. Возвращает разобранные отсчёты."""
        chunk = self.ser.read(4096)
        if chunk:
            self._buf.extend(chunk)
        samples: list[tuple[int, float]] = []
        while True:
            nl = self._buf.find(b"\n")
            if nl < 0:
                break
            raw = bytes(self._buf[:nl])
            del self._buf[: nl + 1]
            # errors='replace': в служебных строках прошивки есть кириллица,
            # а на старте порта в буфер попадает мусор от загрузчика.
            line = raw.decode("utf-8", errors="replace").strip("\r\n \t")
            if not line:
                continue
            if line.startswith("#"):
                self._service(line)
                continue
            parsed = self._data(line)
            if parsed is None:
                # Строка не начинается с '#' и не разбирается как отсчёт. На
                # старте это мусор загрузчика ESP32, в середине потока —
                # признак ошибок на проводе. Считаем, отчёт покажет.
                self.bad_lines += 1
            else:
                samples.append(parsed)
        return samples

    def _service(self, line: str) -> None:
        self.service_lines.append(line)
        body = line.lstrip("#").strip()
        if body.startswith("utro-stage1"):
            self.fw_header = parse_fw_header(body)
            self.fw_header_raw = body
        elif body.startswith("stat "):
            self.last_stat = parse_fw_header(body)
        elif body.startswith("end "):
            self.end_line = parse_fw_header(body)

    @staticmethod
    def _data(line: str) -> tuple[int, float] | None:
        idx, sep, val = line.partition(",")
        if not sep:
            return None
        try:
            return int(idx), float(val)
        except ValueError:
            return None


def wait_for_header(reader: SerialReader, timeout_s: float = 3.0) -> list[tuple[int, float]]:
    """Попросить заголовок и подождать его. Без заголовка мы не знаем ни fs,
    ни версию прошивки, а писать файл с выдуманной частотой нельзя."""
    reader.ser.write(CMD_HEADER)
    reader.ser.flush()
    deadline = time.monotonic() + timeout_s
    spare: list[tuple[int, float]] = []
    while time.monotonic() < deadline:
        spare += reader.poll()
        if reader.fw_header:
            break
        time.sleep(0.05)
    return spare


