# CSV с заголовком-метаданными. Строки, начинающиеся с '#', — метаданные вида
# "# ключ=значение"; они могут стоять и в конце файла (туда дописываются
# счётчики потерь, которые известны только после остановки потока). Дальше —
# обычный CSV: строка имён колонок "index,value" и строки данных.
# Единица значения — СУММА oversample отсчётов АЦП (так отдаёт прошивка);
# для вольт делить на scale и умножать на full_scale_mv/adc_max. Для dsp.py
# масштаб не важен, он инвариантен к усилению.

def _meta_line(key: str, value: object) -> str:
    return f"# {key}={value}\n"


def write_capture_header(fh, meta: dict[str, object]) -> None:
    fh.write(_meta_line(CSV_MAGIC, CSV_FORMAT_VERSION))
    for key, value in meta.items():
        if value is None:
            continue
        fh.write(_meta_line(key, value))
    fh.write(",".join(CSV_COLUMNS) + "\n")


def read_capture(
    path: Path,
) -> tuple[dict[str, str], list[tuple[int, float]], list[str], int]:
    """Прочитать файл записи.

    Возвращает (метаданные, строки, прочие комментарии, число битых строк).
    Ничего не угадывает: неизвестный формат — ошибка, а не предположение.
    """
    meta: dict[str, str] = {}
    comments: list[str] = []
    rows: list[tuple[int, float]] = []
    bad = 0

    def data_lines(fh):
        for raw in fh:
            s = raw.strip()
            if not s:
                continue
            if s.startswith("#"):
                body = s.lstrip("#").strip()
                if "=" in body:
                    k, v = body.split("=", 1)
                    k = k.strip()
                    if k:
                        meta[k] = v.strip()
                        continue
                comments.append(body)
                continue
            yield raw

    with open(path, "r", encoding="utf-8", newline="") as fh:
        reader = csv.reader(data_lines(fh))
        first = True
        for row in reader:
            if first:
                first = False
                if [c.strip() for c in row[:2]] == list(CSV_COLUMNS):
                    continue
                # Заголовка колонок нет — файл писал не этот инструмент.
            if len(row) < 2:
                bad += 1
                continue
            try:
                rows.append((int(row[0]), float(row[1])))
            except ValueError:
                bad += 1

    if CSV_MAGIC not in meta:
        raise ValueError(
            f"{path}: это не запись «Утро» — нет строки '# {CSV_MAGIC}=...'. "
            "Читать такой файл без догадок нельзя."
        )
    return meta, rows, comments, bad


def meta_fs(meta: dict[str, str], override: float | None) -> float:
    """Частота дискретизации из метаданных. Без неё анализ смысла не имеет:
    ошибка в fs линейно переносится в число вдохов и ударов, и человек этого
    не заметит — 15.3 вдоха/мин выглядит так же правдоподобно, как 15.0."""
    if override is not None:
        return override
    raw = meta.get("fs_hz")
    if raw is None:
        raise ValueError(
            "В файле нет fs_hz. Гадать нельзя: неверная частота даст неверное "
            "число вдохов и ударов, и это будет незаметно. Если частота точно "
            "известна — передайте её явно: --fs 200"
        )
    try:
        fs = float(raw)
    except ValueError as exc:
        raise ValueError(f"fs_hz={raw!r} не число") from exc
    if fs <= 0:
        raise ValueError(f"fs_hz={fs} — бессмыслица")
    return fs


