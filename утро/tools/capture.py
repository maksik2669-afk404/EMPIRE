    frac = totals.hr_fraction
    L.append(
        f"Пульс определился в {windows_prep(totals.hr_found)} из "
        f"{totals.counted} ({frac * 100:.0f}%). "
        f"Порог решения — {HR_VERDICT_FAIL * 100:.0f}% "
        "(порог этого инструмента, не из КОМПОНЕНТЫ-УТРО.md)."
    )
    if totals.hr_eligible and totals.counted != totals.hr_eligible:
        L.append(
            f"Окон, где пульс вообще искался (один человек, без шевеления): "
            f"{totals.hr_eligible}, в них найден в "
            f"{totals.hr_found_eligible} "
            f"({totals.hr_fraction_eligible * 100:.0f}%)."
        )
    L.append("")

    if frac < HR_VERDICT_FAIL:
        # Два процента по разные стороны порога — это не вердикт, а вопрос.
        # Знаменатель «все окна» включает окна, в которых метод не мог
        # ответить по построению (пустая постель, шевеление, двое в постели):
        # сходил в туалет на три минуты за десятиминутный замер — и это
        # засчитывалось как свойство матраса. Пример в границах старой
        # защиты: 19 окон, пригодны 13, пульс найден в 5 → 5/19 = 26% (ниже
        # порога, приговор матрасу) против 5/13 = 38% (выше порога). Над
        # вердиктом при этом печаталось «из них пульс найден в 5 (38%)».
        if (
            totals.hr_eligible
            and totals.hr_fraction_eligible >= HR_VERDICT_FAIL
        ):
            L += [
                "ЗАМЕР НЕ ДОКАЗАТЕЛЕН: ДВА ПРОЦЕНТА ПО РАЗНЫЕ СТОРОНЫ ПОРОГА.",
                "",
                f"По всем зачтённым окнам пульс найден в {frac * 100:.0f}% "
                f"({totals.hr_found} из {totals.counted}) — это НИЖЕ порога "
                f"{HR_VERDICT_FAIL * 100:.0f}%.",
                f"По окнам, где его вообще искали (один человек, без "
                f"шевеления), — в "
                f"{totals.hr_fraction_eligible * 100:.0f}% "
                f"({totals.hr_found_eligible} из {totals.hr_eligible}), это "
                "ВЫШЕ порога.",
                "",
                "Разница — окна, в которых метод не имел права отвечать: "
                "пустая постель, шевеление,",
                "двое в постели. Приписывать их матрасу нельзя (встал в туалет "
                "на три минуты — матрас",
                "не виноват), но и выбрасывать из знаменателя нельзя: тогда "
                "достаточно одного удачного",
                "окна из трёхсот.",
                "",
                "Записать заново: один человек, лежать неподвижно 10 минут, не "
                "разговаривать. Тогда оба",
                "процента сойдутся, и ответ будет однозначным.",
            ]
            return EXIT_NO_VERDICT, L

        # Перед приговором матрасу — проверка, не съело ли окна шевеление.
        # analyze_window не ищет пульс при motion=True и при двух людях; если
        # таких окон большинство, запись просто непригодна для вопроса.
        if totals.hr_eligible < max(3, totals.counted * 0.3):
            L += [
                "НА ЭТОЙ ЗАПИСИ ВОПРОС НЕ РЕШАЕТСЯ.",
                "",
                "Окон, в которых DSP вообще имел право искать пульс (один",
                f"человек, без шевеления), всего {totals.hr_eligible} из "
                f"{totals.counted}.",
                "Остальные съело шевеление или второй человек в постели.",
                "Записать заново: один человек, лежать неподвижно 10 минут,",
                "не разговаривать. Матрас здесь ни при чём.",
            ]
            return EXIT_NO_VERDICT, L

        # ПРИГОВОР МАТРАСУ ТРЕБУЕТ ЭТАЛОНА. Он закрывает работающее
        # направление и меняет закупку этапа 2, поэтому выдаётся только когда
        # доказано: (а) эталон дыхания сошёлся — значит мы ловим именно этого
        # человека, а не наводку и не другой файл; (б) эталон пульса ЗАДАН —
        # значит известно, что именно не нашлось, и что у человека в это время
        # вообще был измеримый пульс. Без этого инструмент не имеет права
        # выносить приговор: он не отличает «матрас гасит толчок» от «мы мерили
        # не то».
        if not (ref.resp_given and ref.resp_ok) or not ref.hr_given:
            missing: list[str] = []
            if not ref.resp_given:
                missing.append(
                    "  — не задан --ref-resp: не проверено, что найденные вдохи "
                    "принадлежат этому человеку."
                )
            if not ref.hr_given:
                missing.append(
                    "  — не задан --ref-hr: неизвестно, какой пульс был у "
                    "человека во время записи, то есть"
                )
                missing.append(
                    "    неизвестно даже, было ли что искать (пульсоксиметр на "
                    "палец, одновременно с записью)."
                )
            L += [
                "ЗАМЕР НЕ ДОКАЗАТЕЛЕН: ПУЛЬС НЕ НАЙДЕН, НО ЭТО НЕ ПРИГОВОР "
                "МАТРАСУ.",
                "",
                f"Пульс нашёлся только в {frac * 100:.0f}% окон — это ниже "
                f"порога. Но сказать «на этом матрасе пульса",
                "не будет» на этой записи НЕЛЬЗЯ, потому что не с чем сверить:",
                "",
            ]
            L += missing
            L += [
                "",
                "Этот вывод закрывает работающее направление и меняет закупку "
                "этапа 2, поэтому выдаётся",
                "только под эталон. Повторите замер, сняв ОБА эталона "
                "одновременно с записью:",
                "    --ref-resp <вдохов за минуту, посчитано вручную> "
                "--ref-hr <пульс с пальца>",
                "",
                "Если эталоны сойдутся и пульс всё равно не найдётся — вот "
                "тогда это ответ про матрас.",
            ]
            return EXIT_NO_VERDICT, L

        L += [
            "НА ЭТОМ МАТРАСЕ ПУЛЬСА НЕ БУДЕТ.",
            "",
            "Сердечный толчок до плёнки не доходит: матрас его гасит. Это",
            "свойство матраса, а не ошибка сборки: дыхание проходит И СОШЛОСЬ",
            f"С РУЧНЫМ ПОДСЧЁТОМ ({ref.resp_ref:.1f}/мин), то есть мы ловим",
            f"именно этого человека, а пульс с пальца ({ref.hr_ref:.1f} уд/мин)",
            "в это время был — искать было что.",
            "",
            "ПРОДУКТ ОТ ЭТОГО НЕ УМИРАЕТ. «Утро» остаётся состоятельным без",
            "пульса: дыхание, сон, присутствие и вес — это уже весь продукт.",
            "Утренняя сводка родне и ночные тревоги строятся на них, а не на",
            "пульсе.",
            "",
            "НО ПЛАНЫ НАДО МЕНЯТЬ, И ДО ЗАКУПКИ ЭТАПА 2:",
            "  — выбросить пульс из обещаний продукта и из текстов сводки;",
            "  — присутствие в постели теперь держится только на дыхании и на",
            "    тензодатчиках под ножками, значит тензодатчики из",
            "    «желательно» становятся «обязательно»;",
            "  — если пульс нужен принципиально — это другой датчик (браслет",
            "    или резистивная полоса) и другой разговор про деньги;",
            "  — прежде чем ставить крест: попробовать другой матрас или",
            "    плёнку поверх матраса под простынёй. Это полчаса работы и",
            "    ещё одна запись этим же инструментом.",
        ]
        return EXIT_NO_PULSE, L

    # --- Пик есть. Теперь: пульс ли это? ---
    # ВСЕ ОГОВОРКИ ИДУТ ДО ПОЛОЖИТЕЛЬНОГО ТЕКСТА, А НЕ ПОСЛЕ.
    # Раньше строки «ПУЛЬС ПРОБИВАЕТСЯ / Можно закупать этап 2» попадали в
    # отчёт ДО проверки эталона и тут же опровергались абзацем «НО ЭТО НЕ
    # ПУЛЬС ЧЕЛОВЕКА». Код возврата был правильный (12), а человек в три часа
    # ночи запоминал строку «Можно закупать этап 2». Поэтому текст про закупку
    # не должен попадать в вывод НИ ПРИ КАКОМ несошедшемся эталоне.
    if ref.hr_mismatch:
        L += [
            "ЭТО НЕ ПУЛЬС ЧЕЛОВЕКА. ВОПРОС ОСТАЁТСЯ ОТКРЫТЫМ.",
            "",
            f"Устойчивый пик есть — он нашёлся в {frac * 100:.0f}% окон. Но с "
            "пульсом с пальца он не сошёлся",
            f"({ref.hr_got:.1f} против {ref.hr_ref:.1f} уд/мин, допуск "
            f"±{REF_HR_TOL_BPM:.0f}), а значит измеряет не сердце.",
            "",
            "В полосе 4-20 Гц сидит не только оно: наводка, гармоника "
            "сердечного толчка, гармоника",
            "дыхания, вибрация от холодильника или стиральной машины через пол. "
            "Устойчивый пик —",
            "ещё не пульс.",
            "",
            "Что сделать:",
            "  — пересчитать эталон: пульс с пальца снимать В ТО ЖЕ ВРЕМЯ, что",
            "    и запись, а не до и не после;",
            "  — посмотреть блок КРАТНОСТЬ в сверке выше: если число кратно",
            "    дыханию, это гармоника дыхания, а не сердце;",
            "  — записать заново и сверить снова. Пока не сойдётся, считать,",
            "    что ответа на вопрос этапа 1 нет.",
        ]
        return EXIT_NO_VERDICT, L

    if ref.harmonic_k is not None and not (ref.hr_given and ref.hr_ok):
        # Пик кратен дыханию и эталоном не подтверждён. Выдавать такое за
        # успех нельзя: огибающая кардиополосы модулируется дыханием по
        # построению, то есть эта линия есть в спектре ВСЕГДА, даже когда
        # сердечного толчка в записи нет вовсе.
        L += [
            "ЗАМЕР НЕ ДОКАЗАТЕЛЕН: НАЙДЕННЫЙ ПУЛЬС КРАТЕН ДЫХАНИЮ.",
            "",
            f"Пик нашёлся в {frac * 100:.0f}% окон, медиана "
            f"{ref.hr_got:.1f} уд/мин — но это ровно {ref.harmonic_k}-я "
            f"гармоника",
            f"дыхания ({ref.resp_got:.1f}/мин). Огибающая кардиополосы "
            "модулируется дыханием по построению,",
            "поэтому такая линия стоит в спектре всегда — и когда сердечный "
            "толчок до плёнки доходит,",
            "и когда не доходит. По одному спектру их не отличить.",
            "",
            "Что сделать:",
            "  — снять пульс с пальца одновременно с записью и передать "
            "--ref-hr: если число совпадёт",
            "    в пределах ±3 уд/мин, пик подтверждён;",
            "  — повторить замер, разведя частоты: попросить человека дышать "
            "чуть чаще или реже,",
            "    чтобы пульс перестал быть целым кратным дыхания.",
        ]
        return EXIT_NO_VERDICT, L

    if not ref.hr_given:
        # Пик есть, но сверять его не с чем. Это не успех и не провал: это
        # отсутствие ответа. Прежняя версия в этом месте выдавала «Можно
        # закупать этап 2» и код 0, если был задан хотя бы эталон дыхания.
        L += [
            "ЗАМЕР НЕ ДОКАЗАТЕЛЕН: ПИК ЕСТЬ, ПУЛЬСОМ НЕ ПОДТВЕРЖДЁН.",
            "",
            f"Устойчивый пик найден в {frac * 100:.0f}% окон, медиана "
            f"{totals.hr_median:.1f} уд/мин. Число правдоподобное — и ровно",
            "поэтому опасное: сверять его не с чем. В полосе 4-20 Гц сидит не "
            "только сердце, а",
            "обещание продукта строится на том, что найденное число — это "
            "пульс человека.",
            "",
            "Повторите замер с пульсоксиметром на пальце, снимая пульс "
            "ОДНОВРЕМЕННО с записью:",
            f"    --ref-hr <пульс с пальца>   (допуск сверки "
            f"±{REF_HR_TOL_BPM:.0f} уд/мин)",
            "",
            "Пока этого нет, ответа на вопрос этапа 1 нет — ни «да», ни «нет».",
        ]
        if not ref.resp_given:
            L.append(
                "Эталон дыхания (--ref-resp) тоже не задан: не проверено даже "
                "то, что мы ловим этого человека."
            )
        return EXIT_NO_VERDICT, L

    # Сюда попадаем только когда эталон пульса ЗАДАН и СОШЁЛСЯ, эталон дыхания
    # либо сошёлся, либо не задавался, запись пригодна, ось времени не врёт.
    if frac < HR_VERDICT_GOOD:
        L += [
            "ПУЛЬС ПРОБИВАЕТСЯ, НО НЕУСТОЙЧИВО.",
            "",
            f"{frac * 100:.0f}% окон — это выше порога ({HR_VERDICT_FAIL * 100:.0f}%), "
            "то есть матрас сигнал пропускает,",
            f"и число сошлось с пульсом с пальца ({ref.hr_ref:.1f} уд/мин).",
            "Но на таком проценте строить продуктовое обещание рано.",
            "",
            "Что сделать до закупки этапа 2:",
            "  — переложить плёнку на пару сантиметров (положение под грудью",
            "    решает больше, чем всё остальное) и записать ещё раз;",
            "  — проверить усиление командой \"c 30\": если дыхание занимает",
            "    почти весь диапазон АЦП, пульс тонет в младшем разряде;",
            "  — записать 20 минут вместо 10: больше окон — честнее доля.",
        ]
        code = EXIT_PULSE_SHAKY
    else:
        L += [
            "ПУЛЬС ПРОБИВАЕТСЯ ЧЕРЕЗ ЭТОТ МАТРАС.",
            "",
            "Главный открытый риск этапа 1 закрыт: сердечный толчок доходит до",
            f"плёнки, выделяется устойчиво ({frac * 100:.0f}% окон) и сошёлся с",
            f"пульсом с пальца ({ref.hr_got:.1f} против {ref.hr_ref:.1f} уд/мин).",
            "Можно закупать этап 2.",
        ]
        code = EXIT_PULSE_OK

    if not ref.resp_given:
        L += [
            "",
            "ОГОВОРКА: эталон дыхания (--ref-resp) не задавался. Пульс "
            "подтверждён, но что мы ловим",
            "дыхание именно этого человека — не проверено. Для полной картины "
            "посчитайте вдохи за",
            "минуту и прогоните replay с --ref-resp.",
        ]
    if fs_info is not None and not fs_info.confirmed:
        L += [
            "",
            f"ОГОВОРКА: частота дискретизации не подтверждена прибором "
            f"({fs_info.human}).",
            "Эталон сошёлся, значит грубой ошибки в ней нет, но запас по "
            "точности меньше заявленного.",
            "Измеренную частоту прибор печатает полем fs_meas в строках "
            "'# stat' и '# end'.",
        ]
    return code, L


