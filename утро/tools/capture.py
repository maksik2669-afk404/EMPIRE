# РЕЖИМ raw: ЗАХВАТ СЫРОГО ПОТОКА 4000 Гц
# --------------------------------------------------------------------------

def cmd_raw(args) -> int:
    """Снять сырой поток командой 'r N' и сохранить выгрузку КАК ЕСТЬ.

    Лог пишется дословно, а не переупаковывается в CSV: в выгрузке прошивки
    есть строки '# raw gap', по которым §6.7 отказывает куску в годности, и
    строка '# raw begin' с измеренной частотой. Переписывать их своими словами
    значит взять на себя ответственность за то, что ничего не потеряно.
    """
    out_path = Path(args.out).expanduser()
    out_path.parent.mkdir(parents=True, exist_ok=True)
    seconds = int(args.seconds)
    if not (1 <= seconds <= 30):
        raise SystemExit(
            "--seconds для сырого захвата: от 1 до 30 (прошивка держит захват "
            "в ОЗУ, 8 кБ на секунду)."
        )

    ser = open_serial(args.port, args.baud)
    reader = SerialReader(ser, echo=True)
    written = 0
    try:
        wait_for_header(reader)
        if reader.fw_header:
            print(f"Прошивка: {reader.fw_header_raw}")
        else:
            print(
                "Заголовок не пришёл за 3 с. Захват всё равно попробуем: "
                "частоту возьмём из строки '# raw begin'."
            )
        settle_s = fw_settle_s(reader.fw_header) if reader.fw_header else SETTLE_S_DEFAULT
        print(
            f"Сырой захват {seconds} с на {RAW_RATE_EXPECTED_HZ:g} Гц. Прибор "
            f"сначала ждёт установления тракта {settle_s:.0f} с (§2.4),"
        )
        print(
            f"  потом {seconds} с пишет в ОЗУ, потом выгружает "
            f"{int(seconds * RAW_RATE_EXPECTED_HZ)} строк — это ещё "
            "десятки секунд. Остановить — Ctrl+C."
        )
        print("ВАЖНО: проверка делается при УЛОЖЕННОЙ плёнке и ПУСТОЙ постели (§6.7).")

        ser.write(raw_command(seconds))
        ser.flush()

        # Запас по времени: установление + захват + выгрузка. Выгрузка идёт
        # порциями по мере свободного места в буфере передачи, на 460800 бод
        # 40 000 строк по 11 байт это около 10 с, но на USB-CDC скорость
        # зависит от хоста. Берём с запасом втрое и всё равно выходим по
        # строке '# raw end', а не по таймеру.
        budget = settle_s + seconds + max(60.0, seconds * 12.0)
        deadline = time.monotonic() + budget
        silence = SilenceWatch(settle_s=settle_s)
        done = False
        with open(out_path, "w", encoding="utf-8", newline="") as fh:
            fh.write(_meta_line("written_by", "утро/tools/capture.py raw"))
            fh.write(
                _meta_line(
                    "started_at", datetime.now().astimezone().isoformat(timespec="seconds")
                )
            )
            fh.write(_meta_line("source", f"{args.port} @ {args.baud} (raw)"))
            if args.note:
                fh.write(_meta_line("note", args.note))
            if reader.fw_header_raw:
                fh.write("# " + reader.fw_header_raw + "\n")
            try:
                while time.monotonic() < deadline:
                    # Пишем дословно всё, что приходит: и данные, и служебные
                    # строки прошивки.
                    before = len(reader.service_lines)
                    pairs = reader.poll()
                    if pairs:
                        silence.saw_data()
                    for line in reader.service_lines[before:]:
                        fh.write(line if line.startswith("#") else "# " + line)
                        fh.write("\n")
                    for idx, val in pairs:
                        fh.write(f"{idx},{fmt_value(val)}\n")
                        written += 1
                    silence.check()
                    if reader.service_lines and any(
                        "raw end" in s for s in reader.service_lines[-5:]
                    ):
                        done = True
                        break
                    if not reader.ser.in_waiting:
                        time.sleep(0.02)
            except KeyboardInterrupt:
                print("\nПрерывание.")
        if not done:
            print(
                "ВНИМАНИЕ: строки '# raw end' не дождались — выгрузка могла "
                "оборваться. Файл разобрать всё равно можно,"
            )
            print(
                "  но если в нём меньше строк, чем n в '# raw begin', замер "
                "неполный."
            )
    finally:
        try:
            ser.write(CMD_STOP)
            ser.flush()
        except Exception:                                   # pragma: no cover
            pass
        try:
            ser.close()
        except Exception:                                   # pragma: no cover
            pass

    print(f"Записано {written} сырых отсчётов в {out_path}")
    if written == 0:
        print(
            "Ни одного отсчёта. Проверьте порт и что прошивка свежая: сырой "
            "режим есть только в proto=2."
        )
        return 1
    if args.no_analyze:
        print(
            f"\nРазобрать: python3 {Path(__file__).name} mains {out_path}"
        )
        return EXIT_DONE_NO_VERDICT
    return cmd_mains(argparse.Namespace(file=str(out_path), fs=None))


