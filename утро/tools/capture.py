def cmd_live(args) -> int:
    ser = open_serial(args.port, args.baud)
    reader = SerialReader(ser)
    fh = None
    writer = None
    rows_written = 0

    try:
        spare = wait_for_header(reader)
        if reader.fw_header:
            fw = reader.fw_header
            fs = float(fw.get("fs", FS_EXPECTED_HZ))
            fs_source = "заголовок прошивки"
            print(f"Прошивка: {reader.fw_header_raw}")
        else:
            fw = {}
            if args.assume_fs is None:
                raise SystemExit(
                    "Прошивка не прислала заголовок за 3 с. Без частоты "
                    "дискретизации живая оценка будет врать незаметно.\n"
                    "Задайте частоту явно, если уверены: --assume-fs 200"
                )
            fs = args.assume_fs
            fs_source = "задана вручную (--assume-fs)"

        win_n = int(round(args.window * fs))
        step_n = int(round(args.step * fs))
        if win_n < int(fs * 20):
            raise SystemExit("Окно короче 20 с — analyze_window его не примет.")

        if args.out:
            out_path = Path(args.out).expanduser()
            out_path.parent.mkdir(parents=True, exist_ok=True)
            meta = build_meta(args, fw, fs, fs_source, source=f"{args.port} @ {args.baud} (live)")
            fh = open(out_path, "w", encoding="utf-8", newline="")
            write_capture_header(fh, meta)
            writer = csv.writer(fh, lineterminator="\n")
            print(f"Параллельно пишу в {out_path}")

        asm = StreamAssembler()

        collected: list[WindowReport] = []
        samples_since_eval = 0
        window_no = 0
        silence = SilenceWatch()
        last_lost_said = 0
        deadline = time.monotonic() + args.seconds if args.seconds else None
        # Хвост — последнее непрерывное окно. Держим ровно столько, сколько
        # нужно: при 200 Гц и окне 60 с это 12000 чисел, памяти не жалко, но
        # за сутки без обрезки список вырос бы до 17 млн.
        keep = win_n

        if not args.no_start:
            ser.reset_input_buffer()
            reader._buf.clear()
            spare = []
            ser.write(CMD_START)
            ser.flush()

        def feed(pairs):
            nonlocal samples_since_eval, rows_written
            if pairs:
                silence.saw_data()
            for idx, val in pairs:
                broke = asm.push(idx, val)
                if broke:
                    print(
                        "  РАЗРЫВ ПОТОКА: накопленное окно сброшено, "
                        "отсчёт начинается заново."
                    )
                    samples_since_eval = 0
                samples_since_eval += 1
                if writer is not None:
                    writer.writerow([idx, f"{val:g}"])
                    rows_written += 1

        # Отсчёты, успевшие прийти пока ждали заголовок. При --no-start поток
        # уже идёт, и выбросить их значит молча потерять начало записи; при
        # обычном старте список выше уже очищен вместе с буфером порта.
        feed(spare)

        print(
            f"Живой режим: окно {args.window:g} с, оценка каждые "
            f"{args.step:g} с. Остановить — Ctrl+C."
        )
        print(f"Первая оценка появится через {args.window:g} с.")

        try:
            while True:
                feed(reader.poll())
                silence.check()
                if deadline is not None and time.monotonic() >= deadline:
                    print(f"  Отработано {args.seconds:g} с, останавливаю.")
                    break
                cur = asm.segments[-1] if asm.segments else None
                if cur is not None and len(cur) > keep * 2:
                    # Обрезаем начало, сдвигая start_index: ось времени
                    # сохраняется, номера окон остаются осмысленными.
                    drop = len(cur) - keep
                    cur.start_index += drop
                    del cur.values[:drop]
                    del cur.filled[:drop]

                if (
                    cur is not None
                    and len(cur) >= win_n
                    and samples_since_eval >= step_n
                ):
                    samples_since_eval = 0
                    window_no += 1
                    start = len(cur) - win_n
                    chunk = cur.values[start:]
                    base = chunk[0]                       # см. SUBTRACT_FIRST
                    result = analyze_window([x - base for x in chunk], fs)
                    fill = sum(cur.filled[start:]) / win_n
                    t0 = (cur.start_index + start) / fs
                    rep = WindowReport(window_no, t0, t0 + args.window, result, fill)
                    collected.append(rep)
                    print("  " + format_window_line(rep), flush=True)
                    # Про пропуски говорим только когда счётчик изменился:
                    # повторять одно и то же каждые 30 секунд значит научить
                    # человека не читать эти строки.
                    if asm.stats.lost and asm.stats.lost != last_lost_said:
                        last_lost_said = asm.stats.lost
                        print(
                            f"    пропусков с начала: {samples_nom(asm.stats.lost)}"
                            f" ({asm.stats.lost_fraction * 100:.3f}%), "
                            f"восстановлено вставкой {asm.stats.filled}, "
                            f"разрывов {asm.stats.breaks} — "
                            "итоговый разбор ниже учтёт это",
                            flush=True,
                        )
                if not reader.ser.in_waiting:
                    time.sleep(0.02)
        except KeyboardInterrupt:
            print("\nОстанавливаю.")

        try:
            ser.write(CMD_STOP)
            ser.flush()
            time.sleep(0.2)
            feed(reader.poll())
        except Exception:                                   # pragma: no cover
            pass

        asm.stats.bad_rows = reader.bad_lines
        if fh is not None:
            fh.write(_meta_line("rows", rows_written))
            fh.write(_meta_line("host_lost_by_index", asm.stats.lost))
            fh.write(_meta_line("host_filled", asm.stats.filled))
            fh.write(_meta_line("host_breaks", asm.stats.breaks))
            fh.write(_meta_line("host_bad_lines", reader.bad_lines))
            if reader.end_line.get("lost") is not None:
                fh.write(_meta_line("fw_end_lost", reader.end_line["lost"]))

        started_at, started_src = resolve_started_at(args)
        meta_view = {
            "started_at": started_at,
            "started_at_source": started_src,
            "fw_version": fw.get("fw", "неизвестна"),
            "fw_proto": fw.get("proto", ""),
            "bits": fw.get("bits", ""),
            "oversample": fw.get("oversample", ""),
            "source": f"{args.port} @ {args.baud} (live)",
            "fs_source": "assumed" if not fw else "заголовок прошивки",
            "note": getattr(args, "note", "") or "",
        }
        # В живом режиме окна тоже перекрываются, но они уже напечатаны по
        # мере поступления — второй раз не повторяем.
        return full_report(
            collected, asm.stats, fs, meta_view,
            args.ref_resp, args.ref_hr, quiet_windows=True,
            window_s=args.window,
            step_s=args.step,
            n_segments=len(asm.segments),
            n_usable=len(asm.usable_segments(win_n)),
        )
    finally:
        if fh is not None:
            fh.close()
        try:
            ser.close()
        except Exception:                                   # pragma: no cover
            pass


