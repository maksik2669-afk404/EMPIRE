SETTLE_S_DEFAULT = 46.0

# Заполнение пропусков. Пропущенный отсчёт нельзя просто выбросить: ось
# времени сдвинется, и ВСЯ оценка частоты уедет вверх ровно на долю потерь.
# Короткий пропуск линейно интерполируется — прямая вставка убивает
# содержимое кардиополосы на длине пропуска, но не выдумывает дыхание.
# Граница 0.1 с = 20 отсчётов при 200 Гц: это два периода верхней границы
# кардиополосы (20 Гц) и 0.17% окна 60 с. Значение выбрано рассуждением, на
# железе НЕ проверено: мерить распределением длин реальных пропусков по
# счётчикам lost_pool/lost_tx из строк "# stat".
# Направление влияния вставок проверено на синтетике (morning/synth.py,
# дыхание 15, пульс 63, пропуск 15 отсчётов каждые 60): при доле вставок
# 25% уверенность по пульсу падает с ~19 до ~11, частота остаётся 63.0.
# То есть вставки занижают уверенность, а не создают ложный пульс, — и это
# та сторона ошибки, с которой можно жить. На железе НЕ проверено.
GAP_FILL_MAX_SAMPLES = 20
# Длинный пропуск не заполняется вовсе: на нём запись РАЗРЕЗАЕТСЯ на отрезки,
# и окна никогда не лежат на стыке. Иначе интерполяция длиной в секунды
# попадает прямо в полосу дыхания 0.08-0.7 Гц и читается как вдох.

# Доля вставленных отсчётов в окне. Выше WARN — окно помечается, выше REJECT —
# не идёт ни в медианы, ни в вердикт. 5% окна 60 с это 3 секунды выдуманного
# сигнала; на таком считать пульс нельзя. Пороги — решение, не измерение.
