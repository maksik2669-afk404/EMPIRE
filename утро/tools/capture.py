# Окно и шаг. 60 с — рабочее окно продукта: analyze_window требует минимум
# 20 с, но спектральное разрешение на дыхании при 20 с равно 3 вдоха/мин, а
# при 60 с — 1 вдох/мин, то есть ровно та точность, с которой эталон (ручной
# подсчёт вдохов за минуту) вообще можно сравнивать. Шаг 30 с даёт вдвое
