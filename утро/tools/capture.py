# измерение; на железе НЕ проверено.
CLIP_FRACTION_STOP = 0.001
# Шины известны не всегда (в файле может не быть value_min/value_max). Тогда
# клиппинг ищется как «плоская вершина»: доля отсчётов, РАВНЫХ наблюдаемому
# минимуму или максимуму. У неограниченного сигнала с шумом на экстремум
# попадает единичный отсчёт, у срезанного — проценты. Порог грубее, чем по
# шинам, потому что признак косвенный.
PIN_FRACTION_STOP = 0.01
# Размах выше половины диапазона АЦП — ещё не клиппинг, но запас кончается:
