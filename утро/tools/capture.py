def window_steps(window_s: float, step_s: float, fs: float) -> tuple[int, int]:
    """Длина окна и шаг в ОТСЧЁТАХ. Одна функция на все режимы.

    Раньше арифметика стояла в двух местах и разошлась: analyze_segments
    защищался max(1, ...), а живой режим нет, и `--step 0.001` при 200 Гц
    давал step_n = 0 — полное окно (12000 отсчётов) пересчитывалось на каждой
    итерации опроса порта, живой режим перестал успевать читать порт и начал
    создавать РЕАЛЬНЫЕ потери, о которых потом докладывал как о кабеле.
    """
    win_n = max(1, int(round(window_s * fs)))
    step_n = max(1, int(round(step_s * fs)))
    return win_n, step_n


def check_window_args(window_s: float, step_s: float) -> None:
    """Проверка окна и шага В СЕКУНДАХ, а не через производную от fs.

    Прежний сторож сравнивал win_n с int(fs*20) — обе величины линейны по fs,
    поэтому при fs, близкой к нулю, он вырождался в `0 < 0` и пропускал любое
    окно. Минимум 20 с — требование analyze_window (dsp.py), и оно задано в
    секундах, значит и проверять его надо в секундах.
    """
    if window_s <= 0:
        raise SystemExit("--window должен быть больше нуля")
    if step_s <= 0:
        raise SystemExit("--step должен быть больше нуля")
    if window_s < 20.0:
        raise SystemExit(
            f"Окно {window_s:g} с короче минимума analyze_window (20 с). "
            "Оценка частоты дыхания на таком окне бессмысленна: спектральное "
            "разрешение 20-секундного окна — 3 вдоха/мин, а сверять его надо с "
            "ручным подсчётом за минуту."
        )


# --------------------------------------------------------------------------
# УРОВЕНЬ СИГНАЛА И НАСЫЩЕНИЕ ТРАКТА
# --------------------------------------------------------------------------
# Единственная проверка во всём инструменте, которая видна ПРЯМО В ДАННЫХ и
# не требует веры ни в заголовок, ни в эталон. Насыщение (сигнал прижат к шине
# АЦП) даёт отсутствие пульса на ЛЮБОМ матрасе: срезанная вершина дыхания
# занимает весь диапазон, а сердечный толчок на порядок слабее и живёт в
# младших разрядах, которых уже нет. Срез вдобавок рождает гармоники дыхания
# прямо в полосе пульса 4-20 Гц, то есть может дать ЛОЖНЫЙ пульс.
# Перепутать это со свойством матраса — самая дорогая ошибка этапа 1: человек
# выбросит матрас (или пульс из продукта) вместо того, чтобы крутнуть
# подстроечник усиления.


@dataclass
class LevelStats:
    """Уровень сигнала относительно шин АЦП."""

    n: int = 0
    v_min: float = 0.0
    v_max: float = 0.0
    at_min: int = 0             # отсчётов, РАВНЫХ наблюдаемому минимуму
    at_max: int = 0             # отсчётов, РАВНЫХ наблюдаемому максимуму
    rail_lo: float | None = None
    rail_hi: float | None = None
    at_rail_lo: int = 0
    at_rail_hi: int = 0

    @property
    def span(self) -> float:
        return self.v_max - self.v_min

    @property
    def rails_known(self) -> bool:
        return (
            self.rail_lo is not None
            and self.rail_hi is not None
            and self.rail_hi > self.rail_lo
        )

    @property
    def rail_fraction(self) -> float:
        """Доля отсчётов на шинах. Считается только когда шины известны."""
        if not self.n or not self.rails_known:
            return 0.0
        return (self.at_rail_lo + self.at_rail_hi) / self.n

    @property
    def pinned_fraction(self) -> float:
        """Доля отсчётов на наблюдаемых экстремумах — признак «плоской
        вершины». У неограниченного шумного сигнала на экстремум попадает
        один отсчёт из всей записи, у срезанного — проценты."""
        if not self.n:
            return 0.0
        return (self.at_min + self.at_max) / self.n

    @property
    def span_fraction(self) -> float | None:
        if not self.rails_known:
            return None
        return self.span / (self.rail_hi - self.rail_lo)

    @property
    def clipping(self) -> bool:
        """Насыщение, при котором вердикта о матрасе быть не может."""
        if self.n < 2 or self.span <= 0.0:
            return False
        if self.rails_known and self.rail_fraction > CLIP_FRACTION_STOP:
            return True
        # Без шин — только по плоской вершине, и только когда размах заметно
        # больше единицы младшего разряда: у почти постоянного сигнала
        # «экстремум» это просто самое частое значение, а не срез.
        return self.pinned_fraction > PIN_FRACTION_STOP and self.span >= 20.0

    @property
    def clip_reason(self) -> str:
        if self.rails_known and self.rail_fraction > CLIP_FRACTION_STOP:
            return (
                f"{self.rail_fraction * 100:.2f}% отсчётов лежат на шине АЦП "
                f"(шины {self.rail_lo:g}…{self.rail_hi:g} из метаданных записи)"
            )
        return (
            f"{self.pinned_fraction * 100:.2f}% отсчётов прижаты к крайним "
            f"значениям записи ({self.v_min:g} и {self.v_max:g}) — плоская "
            "вершина, то есть срез"
        )


class LevelAccum:
    """Счётчик уровня за один проход и с постоянной памятью.

    Считать долю отсчётов на экстремуме обычно значит хранить гистограмму, а
    живой режим работает часами. Здесь память не растёт: при появлении нового
    минимума (максимума) счётчик совпадений сбрасывается в единицу, поэтому
    at_min/at_max всегда относятся к ИТОГОВЫМ экстремумам записи.
    """

    def __init__(self, rail_lo: float | None, rail_hi: float | None) -> None:
        self.s = LevelStats(rail_lo=rail_lo, rail_hi=rail_hi)
        # Допуск «на шине»: шина АЦП не всегда достигается ровно (сумма 80
        # отсчётов, младший разряд дребезжит). 0.1% диапазона при шинах
        # 0…327600 это 327 единиц суммы = 4 кода АЦП — меньше, чем шум тракта,
        # и заметно меньше любого полезного сигнала. Значение — решение.
        self.eps = 0.0
        if rail_lo is not None and rail_hi is not None and rail_hi > rail_lo:
            self.eps = (rail_hi - rail_lo) * 0.001

    def add(self, value: float) -> None:
        s = self.s
        if s.n == 0:
            s.v_min = s.v_max = value
            s.at_min = s.at_max = 1
        else:
            if value < s.v_min:
                s.v_min, s.at_min = value, 1
            elif value == s.v_min:
                s.at_min += 1
            if value > s.v_max:
                s.v_max, s.at_max = value, 1
            elif value == s.v_max:
                s.at_max += 1
        s.n += 1
        if s.rails_known:
            if value <= s.rail_lo + self.eps:
                s.at_rail_lo += 1
            elif value >= s.rail_hi - self.eps:
                s.at_rail_hi += 1

    def finish(self) -> LevelStats:
        # При n == 1 экстремум совпадает с единственным отсчётом, и доля
        # «прижатых» равна 2 — поэтому clipping требует n >= 2.
        return self.s


def meta_rails(meta: dict[str, str]) -> tuple[float | None, float | None]:
    """Шины АЦП из метаданных записи (vmin/vmax прошивки)."""
    out: list[float | None] = []
    for key in ("value_min", "value_max"):
        raw = meta.get(key)
        try:
            out.append(float(raw) if raw not in (None, "") else None)
        except ValueError:
            out.append(None)
    return out[0], out[1]


def level_stats(values: list[float], meta: dict[str, str]) -> LevelStats:
    lo, hi = meta_rails(meta)
    acc = LevelAccum(lo, hi)
    for v in values:
        acc.add(v)
    return acc.finish()


def levels_block(levels: LevelStats | None) -> list[str]:
    """Блок отчёта про уровень сигнала. Печатается ВСЕГДА: «размах в норме» —
    такое же нужное сообщение, как и про насыщение, потому что отвечает на
    вопрос «а не надо ли крутить усиление»."""
    if levels is None or levels.n == 0:
        return []
    L = ["УРОВЕНЬ СИГНАЛА (насыщение даёт «пульса нет» на ЛЮБОМ матрасе)"]
    L.append(
        f"  размах отсчётов: {levels.v_min:g}…{levels.v_max:g} "
        f"(размах {levels.span:g})"
    )
    sf = levels.span_fraction
    if levels.rails_known:
        L.append(
            f"  шины АЦП по метаданным: {levels.rail_lo:g}…{levels.rail_hi:g}; "
            f"занято {sf * 100:.1f}% диапазона"
        )
        L.append(
            f"  отсчётов на шине: {levels.at_rail_lo + levels.at_rail_hi} из "
            f"{levels.n} ({levels.rail_fraction * 100:.3f}%)"
        )
    else:
        L.append(
            "  шины АЦП в метаданных не указаны (нет value_min/value_max) — "
            "насыщение ищется только по плоской вершине"
        )
    L.append(
        f"  отсчётов на крайних значениях записи: "
        f"{levels.at_min + levels.at_max} ({levels.pinned_fraction * 100:.3f}%)"
    )
    if levels.clipping:
        L.append("  ТРАКТ В НАСЫЩЕНИИ: " + levels.clip_reason)
        L.append(
            "    Это диагноз ТРАКТА, не матраса. Уменьшите аналоговое усиление "
            "(§6.6) и повторите замер."
        )
    elif sf is not None and sf > SPAN_WARN_FRACTION:
        L.append(
            f"  ВНИМАНИЕ: размах занимает {sf * 100:.0f}% диапазона АЦП — это "
            f"больше половины. Клиппинга ещё нет, но запаса"
        )
        L.append(
            "    почти не осталось: по §6.6 целевой размах дыхания 1850 кодов "
            "из 4095, то есть 45%. Любой вздох глубже"
        )
        L.append("    обычного срежется. Усиление стоит уменьшить.")
    elif sf is not None and sf < 0.01:
        L.append(
            f"  примечание: размах всего {sf * 100:.2f}% диапазона. Если это "
            "запись С ЧЕЛОВЕКОМ — усиления мало, пульс"
        )
        L.append(
            "    сидит в младших разрядах вместе с шумом АЦП; новый G = "
            "текущий * 1850 / (размах в кодах), §6.6."
        )
    return L


@dataclass
class WindowReport:
    """Одно окно: что сказал DSP и насколько окну можно верить."""

    number: int
    t_start_s: float
    t_end_s: float
    result: WindowResult
    fill_fraction: float

    @property
    def rejected(self) -> bool:
        return self.fill_fraction > WINDOW_FILL_REJECT

    @property
    def hr_eligible(self) -> bool:
        """Окно, в котором DSP вообще имел право искать пульс: ровно один
        человек и без шевеления (см. analyze_window). Доля найденного пульса
        по таким окнам — диагностика; вердикт считается по ВСЕМ окнам."""
        return self.result.occupants == 1 and not self.result.motion


def confidence_word(snr: float) -> str:
    """Словами — чтобы отчёт читал человек, а не только скрипт.
    Границы — те же, по которым решает dsp.py."""
    if snr >= PEAK_SNR_RELIABLE:
        return "высокая"
    if snr >= PEAK_SNR_OCCUPIED:
        return "средняя"
    if snr > 0:
        return "низкая"
    return "нет"


def analyze_segments(
    segments: list[Segment],
    fs: float,
    window_s: float,
    step_s: float,
) -> list[WindowReport]:
    """Нарезать отрезки окнами и прогнать каждое через analyze_window."""
    win_n, step_n = window_steps(window_s, step_s, fs)
    reports: list[WindowReport] = []
    number = 0

    for seg in segments:
        if len(seg) < win_n:
            continue
        for start in range(0, len(seg) - win_n + 1, step_n):
            chunk = seg.values[start : start + win_n]
            # ОБЯЗАТЕЛЬНОЕ ВЫЧИТАНИЕ ПЕРВОГО ОТСЧЁТА ОКНА (SUBTRACT_FIRST).
            # Выход зарядового усилителя сидит на середине питания, поэтому в
            # потоке есть постоянное смещение около 163840 (2048*80 — середина
            # диапазона, умноженная на длину скользящей суммы). Биквады в
            # dsp.py стартуют с нулевым состоянием, и для них это ступенька во
            # весь диапазон: переходный процесс попадает в кардиополосу,
            # детектор шевеления видит выброс, ставит motion=True — и пульс не
            # выдаётся вовсе. Ошибка молчаливая: дыхание восстанавливается при
            # любом варианте, и видно её только по пропавшему пульсу.
            #
            # Измерено здесь, на синтетике (morning/synth.py, дыхание 15,
            # пульс 63, смещение 65536, 19 окон по 60 с с шагом 30 с):
            #   без вычитания         пульс  0/19, шевеление 19/19
            #   вычтено среднее окна  пульс 19/19, шевеление  0/19
            #   вычтен первый отсчёт  пульс 19/19, шевеление  0/19
            # Прошивка на своей синтетике получила для среднего 11 из 23, а не
            # полный счёт. Расхождение не разобрано, и это причина НЕ выбирать
            # среднее: первый отсчёт обнуляет ступеньку точно по построению,
            # при любой фазе дыхания в начале окна, а среднее — только когда
            # окно начинается не на вершине вдоха. Вычитать первый отсчёт
            # дешевле и доказуемо, а не статистически.
            # На железе НЕ проверено ни то, ни другое.
            base = chunk[0]
            samples = [x - base for x in chunk]
            result = analyze_window(samples, fs)
            fill = sum(seg.filled[start : start + win_n]) / win_n
            number += 1
            t0 = (seg.start_index + start) / fs
            reports.append(
                WindowReport(
                    number=number,
                    t_start_s=t0,
                    t_end_s=t0 + window_s,
                    result=result,
                    fill_fraction=fill,
                )
            )
    return reports


def plural(n: int, one: str, few: str, many: str) -> str:
    """Русское согласование числительного. Отчёт читает человек, и «1 окон»
    в выводе измерительного прибора подрывает доверие ко всему остальному."""
    n = abs(int(n))
    if n % 10 == 1 and n % 100 != 11:
        return one
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return few
    return many


def windows_nom(n: int) -> str:
    return f"{n} {plural(n, 'окно', 'окна', 'окон')}"


def windows_prep(n: int) -> str:
    """«в 1 окне», «в 3 окнах»."""
    return f"{n} {plural(n, 'окне', 'окнах', 'окнах')}"


def samples_nom(n: int) -> str:
    return f"{n} {plural(n, 'отсчёт', 'отсчёта', 'отсчётов')}"


def mmss(seconds: float) -> str:
    total = int(seconds)
    return f"{total // 60:02d}:{total % 60:02d}"


def format_window_line(rep: WindowReport) -> str:
    r = rep.result
    if r.occupants >= 2:
        occ = "двое"
    elif r.occupied:
        occ = "занято"
    else:
        occ = "пусто"
    resp = f"{r.resp_bpm:5.1f}" if r.resp_bpm is not None else "    —"
    hr = f"{r.hr_bpm:5.1f}" if r.hr_bpm is not None else "    —"
    motion = "ДА " if r.motion else "нет"
    flags = ""
    if rep.rejected:
        flags = f"  ОТБРОШЕНО (вставлено {rep.fill_fraction * 100:.1f}%)"
    elif rep.fill_fraction > WINDOW_FILL_WARN:
        flags = f"  вставлено {rep.fill_fraction * 100:.1f}%"
    return (
        f"окно {rep.number:3d}  {mmss(rep.t_start_s)}–{mmss(rep.t_end_s)}  "
        f"{occ:6s}  дых {resp}/мин  пульс {hr} уд/мин  "
        f"шевеление {motion}  "
        f"увер.дых {confidence_word(r.resp_snr):8s} ({r.resp_snr:5.1f})  "
        f"увер.пульс {confidence_word(r.hr_snr):8s} ({r.hr_snr:5.1f})"
        f"{flags}"
    )


@dataclass
class Totals:
    """Итог по всем окнам, принятым к зачёту."""

    counted: int = 0
    rejected: int = 0
    resp_found: int = 0
    hr_found: int = 0
    hr_eligible: int = 0
    hr_found_eligible: int = 0
    occupied: int = 0
    motion: int = 0
    resp_values: list[float] = field(default_factory=list)
    hr_values: list[float] = field(default_factory=list)

    @property
    def resp_fraction(self) -> float:
        return self.resp_found / self.counted if self.counted else 0.0

    @property
    def hr_fraction(self) -> float:
        return self.hr_found / self.counted if self.counted else 0.0

    @property
    def hr_fraction_eligible(self) -> float:
        return self.hr_found_eligible / self.hr_eligible if self.hr_eligible else 0.0

    @property
    def resp_median(self) -> float | None:
        return statistics.median(self.resp_values) if self.resp_values else None

    @property
    def hr_median(self) -> float | None:
        return statistics.median(self.hr_values) if self.hr_values else None


def summarize(reports: list[WindowReport]) -> Totals:
    t = Totals()
    for rep in reports:
        if rep.rejected:
            t.rejected += 1
            continue
        t.counted += 1
        r = rep.result
        if r.occupied:
            t.occupied += 1
        if r.motion:
            t.motion += 1
        if r.resp_bpm is not None:
            t.resp_found += 1
            t.resp_values.append(r.resp_bpm)
        if rep.hr_eligible:
            t.hr_eligible += 1
        if r.hr_bpm is not None:
            t.hr_found += 1
            t.hr_values.append(r.hr_bpm)
            if rep.hr_eligible:
                t.hr_found_eligible += 1
    return t


